-- עד שנוסף workflow המיגרציות, מיגרציות הורצו ידנית דרך הדשבורד. Supabase
-- רושם הרצה כזו תחת version של **רגע ההרצה** ולא תחת ה-version שבשם הקובץ.
-- התוצאה: מאה רשומות שאין להן קובץ מקביל בריפו.
--
-- למה הן חסמו
-- -----------
-- `supabase db push` מסרב לרוץ כשההיסטוריה במסד מכילה version שאין לו קובץ
-- מקומי, ונכשל ב-"Remote migration versions not found in local migrations
-- directory". שוחזר מקומית מול אותה גרסת CLI: הדגל --include-all *אינו*
-- עוקף את הבדיקה (הוא נועד למקרה ההפוך), ולכן הדרך היחידה קדימה היא
-- `migration repair --status reverted`, שפשוט מוחק את השורות.
--
-- מה המחיקה עשתה — ומה היא לא עשתה
-- ---------------------------------
-- היא נגעה **רק בטבלת הרישום**. הסכימה עצמה לא השתנתה: העמודות, ה-views,
-- ה-policies וה-triggers שהמיגרציות האלה יצרו נשארו בדיוק כפי שהיו. גם אין
-- סיכון שמשהו ירוץ מחדש — אין לשורות האלה קבצים מקומיים.
--
-- שחזור
-- -----
-- אם אי פעם יתברר שהרישום הזה נחוץ, הרצת הקובץ הזה מחזירה אותו כפי שהיה.
-- שימו לב שהחזרתו תחסום שוב את db push, בדיוק מאותה סיבה.
-- ============================================================================

