(function (global) {
  'use strict';

  var MAP = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

  /* ‏null ו-undefined הופכים למחרוזת ריקה ולא ל-"null"/"undefined":
     שדה ריק במסד הוא הרבה יותר שכיח מבאג, והכרטיס צריך להציג כלום. */
  function escapeHtml(s) {
    return String(s === null || s === undefined ? '' : s)
      .replace(/[&<>"']/g, function (c) { return MAP[c]; });
  }

  global.escapeHtml = escapeHtml;
  global.Esc = { html: escapeHtml };
})(window);
