/* ============================================================================
   התאמת טקסט חופשי לשמות - משרדים, יועצי נדל״ן ואזורים
   ----------------------------------------------------------------------------
   החיפוש היה `includes` של המחרוזת כמו שהוקלדה, ולכן "נדלן עפולה" לא מצא את
   "נדל"ן עפולה": גרשיים, גרש, מקף ורווח כפול הם חלק מהשם, ומי שמקליד בטלפון
   כמעט אף פעם לא מקליד אותם (2.11.2026, החיפוש בדף הבית).

   שני כללים:
   1. **נרמול זהה לשני הצדדים** - בלי גרשיים וגרש (כל הצורות), בלי ניקוד,
      סימני פיסוק הופכים לרווח, אותיות סופיות לרגילות, ואותיות לועזיות קטנות.
   2. **כל מילה בשאילתה צריכה להופיע, בכל סדר** - "עפולה נדלן" מוצא את
      "נדל"ן עפולה", ומילה אחת יכולה לבוא מהשם והשנייה מהאזור.

   משותף לדף הבית (assets/home.js), ל-agencies.html ול-agents.html. דף שמשתמש
   בו טוען אותו ב-<script src> לפני הקוד שלו; הקוראים נופלים ל-includes רגיל
   אם הוא חסר, כדי שחיפוש לא יישבר בגלל קובץ שלא נטען.
   ============================================================================ */
(function(){
  var FINALS = { 'ך':'כ', 'ם':'מ', 'ן':'נ', 'ף':'פ', 'ץ':'צ' };

  function norm(s){
    return String(s == null ? '' : s)
      .normalize('NFKC')
      .toLowerCase()
      // ניקוד וטעמים
      .replace(/[֑-ׇ]/g, '')
      // גרשיים וגרש בכל הצורות - נמחקים ולא הופכים לרווח: נדל"ן = נדלן
      .replace(/["'`׳״“”„‘’´]/g, '')
      // שאר הפיסוק מפריד מילים
      .replace(/[.,;:!?()\[\]{}\/\\|&+*_~·‐-―−-]/g, ' ')
      .replace(/[ךםןףץ]/g, function(c){ return FINALS[c]; })
      .replace(/\s+/g, ' ')
      .trim();
  }

  // ‏haystack: מחרוזת או מערך של שדות. ‏query ריק מתאים לכל דבר.
  function matches(haystack, query){
    var q = norm(query);
    if (!q) return true;
    var h = norm(Array.isArray(haystack) ? haystack.filter(Boolean).join(' ') : haystack);
    // ‏"רי/מקס" נשמר כ"רי מקס", ומי שמחפש/ת "רימקס" לא מקליד/ה את הרווח:
    // מילה שלא נמצאה נבדקת גם מול השדות בלי רווחים
    var compact = h.replace(/ /g, '');
    var words = q.split(' ');
    for (var i = 0; i < words.length; i++){
      if (h.indexOf(words[i]) === -1 && compact.indexOf(words[i]) === -1) return false;
    }
    return true;
  }

  window.TextMatch = { norm: norm, matches: matches };
})();
