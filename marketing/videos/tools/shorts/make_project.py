"""Fill a Reelkit project (made with `reelkit init ... --aspect 9:16 --private`) for one short.

Usage: python3 -I make_project.py <transcript.json> <snapped.json> <segment id> <project-dir> [--drop-fillers]

Writes into <project-dir>:
  plan.json        footage mode, no generated voice, equal slices that add up to the clip
  src/Words.tsx     the clip's words with times RELATIVE TO THE CLIP (what <Captions> draws) and the two hook lines
  src/Video.tsx    the composition (copied from shorts/Video.tsx next to the tools' parent folder)

Edit src/Words.tsx by hand (or ask Claude to) to fix recognition errors: change `word`, never a time.
The captions must say what the speaker says, so nothing is reworded or tidied beyond a wrong word.
"""
import json
import os
import shutil
import sys

args = [x for x in sys.argv[1:] if not x.startswith("--")]
drop = "--drop-fillers" in sys.argv
tr_path, snap_path, seg_id, proj = args[0], args[1], int(args[2]), args[3]

FILLERS = {"אה", "אהה", "אמ", "אמם", "אממ", "אההה", "המ", "הממ", "אההם", "אוף"}

tr = json.load(open(tr_path))
seg = next(s for s in json.load(open(snap_path))["segments"] if s["id"] == seg_id)
t0, t1 = seg["start"], seg["end"]
words = []
for w in tr["words"]:
    if w["endSec"] <= t0 or w["startSec"] >= t1:
        continue
    if drop and w["word"].strip(".,?!…") in FILLERS:
        continue
    st = max(0.0, w["startSec"] - t0)
    en = min(t1 - t0, w["endSec"] - t0)
    words.append({"word": w["word"], "startSec": round(st, 3), "endSec": round(max(en, st + 0.04), 3)})
if not words:
    sys.exit("no words in that segment")

h1, h2 = seg.get("hook1", ""), seg.get("hook2", "")
text = " ".join(w["word"] for w in words)
dur = round(t1 - t0, 2)
# Reelkit wants 3 to 16 scenes of at most 15 s each when there is no generated voice. The scenes here are
# only slices of the clip's clock (the composition draws captions and hook once, on the global clock), so
# they are equal parts that add up to the clip's length.
import math
# 0.1 s shorter than the clip: the scenes may not run past the footage, and frame rounding adds up
span = math.floor((dur - 0.1) * 100) / 100
n = max(3, math.ceil(span / 14))
cuts = [round(span * k / n, 2) for k in range(n)] + [span]
scenes = []
for k in range(n):
    lo, hi = cuts[k], cuts[k + 1]
    part = " ".join(w["word"] for w in words if lo <= w["startSec"] < hi) or "-"
    scenes.append({
        "id": f"part-{k + 1}", "seconds": round(hi - lo, 2), "narration": part,
        "treatment": "footage-overlay",
        "onScreenText": [t for t in (h1, h2) if t] if k == 0 else [],
        "imagePrompt": None, "clipPrompt": None, "shareable": False, "imageTags": [], "userAssetIds": [],
        "notes": (f"short from a long recording, {t0:.1f}-{t1:.1f}s ({dur}s), score {seg.get('score')}. "
                  "The speaker's own sound plays and the picture is already 9:16 (face-tracked). "
                  "Hebrew captions and the hook are drawn once for the whole clip from src/Words.tsx; "
                  "these scenes are only slices of the clock.") if k == 0 else "same clip, next slice",
    })
plan = {
    "title": h1 or f"short {seg_id}", "aspect": "9:16", "mode": "footage", "voice": "none",
    "pace": "normal", "gap": "normal", "captions": "phrase", "scenes": scenes,
}
os.makedirs(f"{proj}/src", exist_ok=True)
json.dump(plan, open(f"{proj}/plan.json", "w"), ensure_ascii=False, indent=2)
# a .tsx module and not .json: `reelkit check` only allows imports of react, reelkit and component files
open(f"{proj}/src/Words.tsx", "w").write(
    "// Generated by marketing/videos/tools/shorts/make_project.py. Fix a wrong word by editing `word`; never a time.\n"
    f"export const Words = {json.dumps(words, ensure_ascii=False, indent=1)};\n"
    f"export const Hook = {json.dumps({'hook1': h1, 'hook2': h2}, ensure_ascii=False)};\n")
shutil.copy(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "shorts", "Video.tsx"), f"{proj}/src/Video.tsx")
print(f"{len(words)} words, {dur}s -> {proj}")
