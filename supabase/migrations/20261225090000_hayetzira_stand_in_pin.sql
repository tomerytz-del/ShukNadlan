-- רחוב היצירה: פין זמני מהכתובת הצמודה, עד שהרחוב ייכנס לשכבה
--
-- ## מה שהתברר, והוא מתקן נימוק שגוי במיגרציה הקודמת
--
-- ‏`20261224090000` מחקה את הפין של מודעה #1066 בהנחה שהוא "הועתק מבניין
-- אחר" ושהתור יפתור את הכתובת מחדש. **שתי ההנחות היו שגויות**, וההרצה
-- הראתה זאת מיד: התור החזיר `address_not_found`, והמודעה נשארה בלי פין.
--
-- הסיבה היא ש-**רחוב היצירה אינו קיים בשכבת הכתובות של העירייה בכלל**:
--
--   street_registry · עפולה · היצירה
--     source = 'legacy' · last_seen_at = null · active = false
--
-- כלומר סנכרון ה-GIS מעולם לא מצא אותו. זה רחוב חדש בעפולה, ורשומות
-- העירייה עדיין לא הדביקו אותו. ‏**שום מספר בית בהיצירה לא יתגאוקד**,
-- ולא רק 3.
--
-- ומכאן גם שהפין שכל חמש המודעות בהיצירה 5 נושאות -
-- ‏`32.601334 / 35.2940907` - **לא יכול היה להגיע מהשכבה**. הוא הוזן ביד.
-- ההבחנה גלויה בדיוק העשרוני: פין שנפתר מהשכבה נראה כמו
-- ‏`32.6053162641914`, והזנה ידנית נראית כמו `32.601334`.
--
-- **הלקח:** לפני שמאפסים מונה או מוחקים פין, בודקים את `source` של הרחוב
-- במרשם. ‏`docs/geocoding.md` כבר אומר זאת במפורש - "רחוב `legacy` פירושו
-- שהרחוב אינו בשכבה, ואיפוס המונה רק ישרוף שלושה ניסיונות נוספים" - ואני
-- לא בדקתי. השאילתה היא שורה אחת.
--
-- ## ההחלטה: פין של הכתובת הצמודה, ובמפורש כזמני
--
-- החלטת מנהל/ת הפלטפורמה: עד שהרחוב יתעדכן ברשומות, מודעות היצירה יוצגו
-- על **המלאכה 25** - הכתובת הצמודה באזור התעשייה.
--
-- **הכתובת עצמה אינה משתנה.** ‏`street` ו-`address` נשארים `היצירה 5`,
-- כי זו הכתובת האמיתית ומה שהסוכן/ת והלקוח/ה רואים. מה שזז הוא הפין
-- בלבד. זו ההפרדה הנכונה: כתובת שקרית הייתה נשלחת ללקוח/ה ומודפסת בדוח,
-- ופין זמני הוא שגיאת מיקום של 60 מ' במפה.
--
-- **הפין שנבחר הוא `32.6018463 / 35.29445`**, ולא הפין הידני שהיה. זה
-- הערך ששתי מודעות עצמאיות בהמלאכה 25 (#1055 ו-#1071) קיבלו, ו-`המלאכה`
-- הוא רחוב `gis` פעיל שנראה בסנכרון ב-14.9.2026 - כלומר זה הערך שהשכבה
-- מחזירה, ולא עוד ניחוש ידני. המרחק בין שני הפינים הוא כ-66 מ'.
--
-- ## ואיך מחזירים כשהרחוב ייכנס לרשומות
--
-- הסימן הוא שורת המרשם עצמה. כששכבת העירייה תכלול את היצירה, הסנכרון
-- יעדכן אותה ל-`source = 'gis'` עם `active = true`, וזו השאילתה שבודקת:
--
--   select source, active, last_seen_at
--     from public.street_registry
--    where city = 'עפולה' and name = 'היצירה';
--
-- ומרגע שזה קרה, ההחזרה היא מחיקת הפין - לא כתיבה של ערך חדש:
--
--   update public.properties
--      set lat = null, lng = null,
--          geocode_attempts = 0, geocode_attempted_at = null, geocode_error = null
--    where city = 'עפולה' and street = 'היצירה'
--      and lat = 32.6018463 and lng = 35.29445;
--
-- התנאי על הקואורדינטה הוא מה ששומר על ההחזרה מדויקת: הוא נוגע **רק**
-- במודעות שנושאות את הפין הזמני הזה, ולא במודעה שבינתיים קיבלה פין אמיתי
-- או שהוזן לה משהו אחר ביד. אין כאן דגל חדש בסכימה, כי הקואורדינטה עצמה
-- היא הסימן, והיא מדויקת דיה.
-- ============================================================================

-- ‏1. חמש המודעות בהיצירה 5: הפין הידני מוחלף בפין של המלאכה 25.
--    הכתובת אינה נוגעת, ולכן `property_dedupe_key` אינו משתנה והטריגר
--    יוצא מיד ביציאה המוקדמת שלו.
update public.properties
   set lat = 32.6018463,
       lng = 35.29445
 where city = 'עפולה'
   and street = 'היצירה'
   and (lat is distinct from 32.6018463 or lng is distinct from 35.29445);

-- ‏2. מודעה #1066 הועברה בינתיים ידנית ל-`המלאכה 25`, ונשארה עליה
--    הקומבינציה הגרועה: הפין הידני של היצירה, ועוד `address_not_found`
--    שהמיגרציה הקודמת כתבה. שתי הכתובות באותו בניין, ולכן היא מקבלת את
--    הפין של שכנותיה - והשגיאה מנוקה, כי היא מתארת ניסיון על כתובת שכבר
--    אינה הכתובת של המודעה.
update public.properties
   set lat = 32.6018463,
       lng = 35.29445,
       geocode_attempts     = 0,
       geocode_attempted_at = null,
       geocode_error        = null
 where city = 'עפולה'
   and street = 'המלאכה'
   and house_number = '25'
   /* מכוון בצמצום: רק שורה שנושאת את הפין הידני של היצירה, או שאין לה
      פין, או שנשארה עליה שגיאה. מודעה בהמלאכה 25 שיש לה פין תקין משלה
      אינה נדרסת - ייתכן בהחלט שלבניין יש יותר מכניסה אחת. */
   and ((lat = 32.601334 and lng = 35.2940907)
        or lat is null or lng is null
        or geocode_error is not null);

-- ============================================================================
-- דיווח
-- ============================================================================

do $$
declare
  v_yetzira  integer;
  v_melacha  integer;
  v_stray    integer;
begin
  select count(*) into v_yetzira
    from public.properties
   where city = 'עפולה' and street = 'היצירה'
     and lat = 32.6018463 and lng = 35.29445;

  select count(*) into v_melacha
    from public.properties
   where city = 'עפולה' and street = 'המלאכה' and house_number = '25'
     and lat = 32.6018463 and lng = 35.29445;

  select count(*) into v_stray
    from public.properties
   where city = 'עפולה' and street in ('היצירה', 'המלאכה')
     and status = 'active'
     and (lat is null or lng is null);

  raise notice 'היצירה עם הפין הזמני: % · המלאכה 25: % · פעילות בלי פין: %',
    v_yetzira, v_melacha, v_stray;

  if v_stray > 0 then
    raise warning 'נשארה מודעה פעילה בלי פין באחד משני הרחובות - כדאי מבט';
  end if;
end $$;
