-- ---------------------------------------------------------------------------
-- ‏market_cities_public - מזהה עיר ו-slug של שוק, ולא יותר
--
-- **למה view נפרד ולא הרחבה של cities_public:** ‏cities_public הוא "הערים
-- החיות" - התפריט, דף העיר וה-sitemap נשענים על כך שכל שורה בו חיה. כאן
-- צריך גם ערים שעוד לא נפתחו: דף הבית של עפולה מסנן **החוצה** את ערי חיפה
-- כבר היום, עוד לפני שחיפה חיה, כדי שנכס שמשרד בחיפה מעלה לא יופיע בעפולה.
--
-- **מה נחשף:** מזהה (uuid) ו-slug של שוק. שני אלה כבר פומביים בפועל -
-- ה-slug-ים ב-assets/markets.js, והמזהה על כל נכס (`properties.city_id`).
-- **השם של העיר אינו כאן**, ולכן ה-view אינו עונה על "אילו ערים הם
-- עומדים להשיק" - השאלה שבגללה cities_public מסנן לפי is_live.
--
-- בלי security_invoker, בדיוק כמו cities_public: הסינון הוא ה-where,
-- ועמודות התפעול אינן כאן.
-- ---------------------------------------------------------------------------
create or replace view public.market_cities_public as
select c.id as city_id, c.market_slug
  from public.cities c
 where c.active and c.market_slug is not null;

comment on view public.market_cities_public is
  'מזהה עיר ← slug של שוק, לסינון לפי שוק בדפדפן. בלי שמות ערים, בכוונה: הוא אינו חושף אילו ערים עומדות להיפתח. docs/regional-pages.md';

grant select on public.market_cities_public to anon, authenticated;
