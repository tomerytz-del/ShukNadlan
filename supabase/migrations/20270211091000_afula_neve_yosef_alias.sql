-- ============================================================================
-- "נווה יוסף" ו"נוף יזרעאל" - כינויים של גבעת המורה בעפולה
--
-- במאגר רשות המיסים 29 עסקאות רשומות תחת "נווה יוסף", ואין לנו שכונה בשם
-- הזה, ולכן הן נשארו בלי שיוך (`neighborhood_ids` null). תשעה רחובות, כולם
-- רחובות הפרחים: הסביון (12), הנורית (4), האירוסים, החרצית (3 כל אחד),
-- החצב, הסייפן (2), הסחלב, הסיתונית, פעמונית (1). אף אחד מהם אינו מופיע ב-
-- 118 העסקאות של "גבעת המורה", ו-26 מתוך 29 העסקאות נופלות במצולע של גבעת
-- המורה (לשלוש האחרות אין פין).
--
-- ההכרעה (מנהל הפלטפורמה, 4.10.2026): זה אזור קטן בתוך גבעת המורה שנקרא
-- שכונת נוף יזרעאל. אין אצלנו תת-שכונה - שורה ב-`neighborhoods` הייתה
-- מופיעה כשכונה בסינון של דף הבית ובחיפוש החכם - ולכן שני השמות נרשמים
-- ככינויים של גבעת המורה, לא כשכונה משלהם.
--
-- הטריגר `neighborhood_aliases_relink_deals` משייך מחדש את עסקאות העיר
-- מעצמו, ולכן אין כאן update. ‏`on conflict do nothing` - המיגרציה בטוחה
-- להרצה חוזרת.
-- ============================================================================

insert into public.neighborhood_aliases (neighborhood_id, alias, shared, note)
select n.id, v.alias, false, v.note
  from (values
    ('נווה יוסף',  'השם במאגר רשות המיסים לשכונת נוף יזרעאל, אזור קטן בגבעת המורה (הכרעת מנהל הפלטפורמה, 4.10.2026)'),
    ('נוף יזרעאל', 'אזור קטן בגבעת המורה (הכרעת מנהל הפלטפורמה, 4.10.2026)')
  ) as v(alias, note)
  join public.cities c on c.name = 'עפולה'
  join public.neighborhoods n on n.city_id = c.id and n.name = 'גבעת המורה'
on conflict (neighborhood_id, alias_key) do nothing;
