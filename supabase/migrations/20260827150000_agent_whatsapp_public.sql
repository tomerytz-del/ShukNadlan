-- ============================================================================
-- מספר הוואטסאפ של הסוכן/ת המטפל/ת — חשיפה לעמוד הנכס הציבורי
--
-- בעמוד הנכס יש בועה צפה שפותחת שיחת וואטסאפ עם הסוכן/ת שמטפל/ת בנכס
-- (‏properties.agent_id). כדי שהדפדפן של גולש/ת אנונימי/ת יוכל לבנות את
-- הקישור, ה-view הציבורי צריך להחזיר את המספר — עד היום הוא החזיר שם,
-- תמונה ותפקיד בלבד.
--
-- נחשף ‏phone_e164 ולא ‏phone: זו עמודה מחושבת (ראו whatsapp_integration)
-- שמכילה ספרות בלבד בפורמט 972521112222 — בדיוק מה ש-wa.me מצפה לו, ולכן
-- אין נרמול בצד הלקוח. סוכן/ת בלי טלפון מקבל/ת null, והבועה פשוט לא מוצגת.
--
-- החשיפה מכוונת: מספר הטלפון של מתווך/ת הוא פרט קשר עסקי שמפורסם ממילא על
-- כל מודעה, וזו כל תכלית הבועה. עדיין נחשפים רק סוכנים פעילים
-- (‏active = true), כמו בכל שאר העמודות ב-view.
-- ============================================================================

-- ‏create or replace שומר על סדר העמודות הקיים ומוסיף את החדשה בסוף.
-- ה-view נשאר בלי security_invoker (התבנית הקיימת בפרויקט): ה-RLS על
-- ‏agency_members חוסם קריאה ישירה של anon, וה-view הוא שער הקריאה המבוקר.
create or replace view public.agency_members_public as
select
  id,
  agency_id,
  slug,
  display_name,
  bio,
  photo_url,
  role,
  active,
  phone_e164
from public.agency_members
where active = true;

comment on view public.agency_members_public is
  'פרופיל ציבורי של סוכנים פעילים, כולל phone_e164 לצורך קישורי wa.me בעמודי הנכס והמשרד. אינו חושף אימייל, מצב חיוב או נתוני מנוי.';

-- ---------------------------------------------------------------------------
-- הידוק הרשאות
--
-- ‏view פשוט על טבלה אחת הוא auto-updatable, ומכיוון שהוא רץ בהרשאות הבעלים
-- (בלי security_invoker) כתיבה דרכו הייתה עוקפת את ה-RLS על agency_members.
-- ברירת המחדל של Supabase נותנת ל-anon ול-authenticated הרשאות מלאות על כל
-- ה-view-ים בסכימה, ולכן צריך לצמצם במפורש לקריאה בלבד — אותה תבנית שכבר
-- הופעלה כאן על shared_properties_for_me ועל rss_leads_public.
-- ---------------------------------------------------------------------------
revoke all on public.agency_members_public from anon, authenticated;
grant select on public.agency_members_public to anon, authenticated;
