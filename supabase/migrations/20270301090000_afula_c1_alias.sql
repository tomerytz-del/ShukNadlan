-- ============================================================================
-- "C1" ו"לב העמק" - שני שמות של אותה שכונה בעפולה
--
-- השכונה רשומה אצלנו "לב העמק C1". גולשים כותבים "C1", "סי 1" או "C-1",
-- ובמאגר רשות המיסים היא עשויה להופיע כ"לב העמק" בלבד. ב-4.10.2026 שני
-- גולשים שאלו את גבריאלה על "סי 1" ו"c-1" וקיבלו "לא מצאתי", כשבמלאי היו
-- שש דירות מתאימות שם.
--
-- ההכרעה (מנהל הפלטפורמה, 5.10.2026): שכונת C1 היא שכונת לב העמק. שלושת
-- הכתיבים נרשמים ככינויים, ו-`search_properties` בבוט הציבורי קורא מכאן.
--
-- הטריגר `neighborhood_aliases_relink_deals` משייך מחדש את עסקאות העיר
-- מעצמו, ולכן אין כאן update. ‏`on conflict do nothing` - בטוחה להרצה חוזרת.
-- ============================================================================

insert into public.neighborhood_aliases (neighborhood_id, alias, shared, note)
select n.id, v.alias, false, v.note
  from (values
    ('לב העמק', 'שכונת C1 היא שכונת לב העמק (הכרעת מנהל הפלטפורמה, 5.10.2026)'),
    ('C1',      'שכונת C1 היא שכונת לב העמק (הכרעת מנהל הפלטפורמה, 5.10.2026)'),
    ('סי 1',    'כתיב עברי של C1 (הכרעת מנהל הפלטפורמה, 5.10.2026)')
  ) as v(alias, note)
  join public.cities c on c.name = 'עפולה'
  join public.neighborhoods n on n.city_id = c.id and n.name = 'לב העמק C1'
on conflict (neighborhood_id, alias_key) do nothing;
