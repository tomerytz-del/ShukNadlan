-- ===========================================================================
-- properties.has_own_garden: לדירה רגילה יש גינה
--
-- "דירה עם גינה" היא דירת גן (assets/search-core.js, typeIn), אבל יש גם דירות
-- שסווגו "דירה" ויש להן גינה צמודה - למשל בקומה 2 - ותומר ביקש (27.11.2026)
-- שגם הן יופיעו בתוצאות. ‏property_type לבדו לא מספיק: מ-145 הדירות הפעילות
-- 26 עם `garden_sqm`, ועוד דירות שהתיאור שלהן מזכיר גינה.
--
-- עמודה מחושבת (‏stored, כמו street_key): נכס נחשב בעל גינה אם
--   • `garden_sqm` > 0 **וקומה 3 ומטה** (או בלי קומה). מ-12 הדירות שבקומות 4-8
--     ושל גינה בת 6-35 מ"ר, רובן ככל הנראה מרפסת או גג שהוזנו בשדה הגינה, והן
--     נשארות בחוץ. הסף הוא קו אחד כאן; שינוי שלו הוא drop ו-add של העמודה.
--   • או שהתיאור שכתב הסוכן/ת מזכיר "גינה", ואינו מדבר על גינה **משותפת או
--     ציבורית** ("לבניין גינה משותפת לדיירים"), ואינו "בלי/ללא/אין גינה".
-- ‏`marketing_description` אינו נבדק: הוא נגזר מ-garden_sqm ומהתיאור, ולכן
-- היה מחזיר את הדירות שהסף למעלה הוציא.
--
-- נמדד בפרודקשן (קריאה בלבד) לפני ההוספה: 15 דירות פעילות עם garden_sqm בקומה 3
-- ומטה, ועוד 2 מהתיאור (1144, 1518).
--
-- ‏**האתר אינו קורא את העמודה ב-PROPERTY_SELECT**: עמודה חסרה הייתה מפילה את
-- שליפת הנכסים כולה (נתוני דמו), והאתר עולה לפני המיגרציה. ‏`loadGardenIds`
-- שולף ‏id בלבד בשאילתה נפרדת, וכישלון שלה אינו משנה דבר.
--
-- אידמפוטנטית. אין הרשאות ברמת עמודה על properties (attacl ריק), ולכן ההרשאה
-- ברמת הטבלה חלה גם על העמודה החדשה, כמו street_key.
-- ===========================================================================

alter table public.properties
  add column if not exists has_own_garden boolean
  generated always as (
    coalesce(garden_sqm, 0) > 0 and coalesce(floor, 0) <= 3
    or coalesce(
         description ~ 'גינ'
         and description !~ 'גינ[הת]? ?(משותפ|ציבורי|שכונתי)'
         and description !~ '(לבניין|בבניין|לדיירים|לשכנים|משותפת|ציבורית) ?גינ'
         and description !~ '(ללא|בלי|אין) גינ',
         false)
  ) stored;

comment on column public.properties.has_own_garden is
  'דירה/נכס עם גינה צמודה: garden_sqm > 0 בקומה 3 ומטה, או "גינה" בתיאור שאינה משותפת/ציבורית. מחושבת. 20271202170000. משמשת את "דירה עם גינה" באתר.';
