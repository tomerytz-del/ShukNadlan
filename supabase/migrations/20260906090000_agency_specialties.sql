-- ============================================================================
-- תחומי ההתמחות של המשרד
--
-- ‏specialty_areas (שכבר קיימת) עונה על השאלה "איפה" — עפולה, מגדל העמק,
-- הכפרים. ‏specialties עונה על השאלה "במה": פינוי בינוי, קרקעות, נכסים
-- מניבים, מסחרי וכו׳. שתי שאלות שונות ולכן שתי עמודות, ובדף המשרד הן מוצגות
-- כשתי שורות תגיות נפרדות.
--
-- העמודה היא הצהרה של המשרד ולא נגזרת: משרד שמתמחה בהתחדשות עירונית מצהיר
-- על כך גם לפני שעלה לו נכס אחד כזה. במקביל דף המשרד יודע לגזור תגיות
-- מתוך הנכסים בפועל (ראו assets/specialties.js), וזו נפילה־לאחור למשרד
-- שעדיין לא בחר — לא תחליף לבחירה.
--
-- שימו לב: ‏agency_members.specialties (של הסוכן/ת) הוא טקסט חופשי עד 8 תגיות,
-- והעמודה כאן אינה הרחבה שלו אלא דבר אחר. סוכן/ת מנסח/ת את ההתמחות במילים
-- שלה; משרד נכנס לרשימה סגורה, כי לפי התגיות האלה אפשר יהיה לסנן משרדים.
--
-- אוצר המילים סגור ברמת ה-DB ולא רק בטופס: תגיות חופשיות היו הופכות תוך
-- חודש ל"פינוי בינוי", "פינוי-בינוי" ו"התחדשות עירונית" כשלושה ערכים
-- שונים, ואי אפשר היה לסנן משרדים לפיהן. הרשימה חייבת להישאר זהה ל-
-- ‏SPECIALTY_CATALOG ב-assets/specialties.js.
--
-- תקרה של 6: משרד שמסמן הכל לא אמר כלום, ובדף עצמו שורת תגיות ארוכה
-- דוחפת את כל מה שמתחתיה מתחת לקיפול.
--
-- הקובץ אידמפוטנטי.
-- ============================================================================

alter table public.agencies
  add column if not exists specialties text[] not null default '{}';

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'agencies_specialties_check') then
    alter table public.agencies
      add constraint agencies_specialties_check
      check (
        cardinality(specialties) <= 6
        and specialties <@ array[
          'residential_sale',    -- קנייה ומכירה של נכסים פרטיים
          'residential_rent',    -- השכרת דירות ובתים
          'commercial',          -- נכסים מסחריים — חנויות, שטחי מסחר, משרדים
          'income',              -- נכסים מניבים ולהשקעה
          'land',                -- קרקעות, מגרשים ונחלות
          'urban_renewal',       -- פינוי בינוי והתחדשות עירונית
          'new_projects',        -- פרויקטים חדשים מקבלן
          'luxury',              -- נכסי יוקרה ווילות
          'industrial',          -- מבני תעשייה, מחסנים ולוגיסטיקה
          'property_management'  -- ניהול נכסים עבור בעלים
        ]::text[]
      );
  end if;
end $$;

comment on column public.agencies.specialties is
  'תחומי ההתמחות שהמשרד הצהיר עליהם (אוצר מילים סגור, עד 6). נפרד מ-specialty_areas שהם אזורי הפעילות הגאוגרפיים.';
