-- שוק חדרה והסביבה: כינויי שכונות לשמות שרשות המיסים כותבת אחרת, וכינוי עיר
--
-- אחרי ייבוא השכונות מ-GovMap (21.11.2026, 112 שכונות בשוק) ההצלבה מול
-- market_deals_official מצאה שמות שכונה ברשות המיסים שאינם השם שלנו, אבל
-- הם אותה שכונה: "נוף ים - מע"ר" מול "נוף ים", "עמידר" מול "עמידר (גבעת
-- עדה)", ובקיסריה "3 - הצמרות" מול "שכונה 3". בלי כינוי, עסקה בלי פין
-- בשכונה כזו אינה נכנסת להשוואה לפי שכונה, ו"עסקאות בהצמרות" בוואטסאפ
-- חוזר ריק. רק זוגות שהם אותה שכונה בוודאות; "המושבה" בבנימינה-גבעת עדה
-- (שתי מושבות) ו"כרכור" (אזור שלם) נשארים בחוץ. "אזור תעשיה" ו"וייצמן"
-- כבר נפתרים ב-neighborhood_name_key ואינם כאן.
--
-- הטריגר על neighborhood_aliases מקשר מחדש את העסקאות של העיר מעצמו
-- (neighborhood_relink_deals, 20270114091000).
--
-- וכינוי עיר אחד: "זיכרון יעקב" (הכתיב המלא) ל"זכרון יעקב" - מה שאנשים
-- מקלידים, ומה שרשות המיסים כותבת בשם השכונה "חלומות זיכרון".

insert into public.neighborhood_aliases (neighborhood_id, alias, shared, note)
select n.id, v.alias, false, 'השם במאגר רשות המיסים (הצלבה אחרי ייבוא GovMap, 21.11.2026)'
  from (values
    ('אור עקיבא',        'אזור תעשייה צפוני',  'אזור תעשיה צפון'),
    ('אור עקיבא',        'נוף ים',             'נוף ים - מע"ר'),
    ('אור עקיבא',        'המרכז הוותיק',       'אור עקיבא הותיקה'),
    ('בנימינה-גבעת עדה', 'עמידר (גבעת עדה)',   'עמידר'),
    ('בנימינה-גבעת עדה', 'יפה נוף (גבעת עדה)', 'יפה נוף'),
    ('בנימינה-גבעת עדה', 'יוספטל (גבעת עדה)',  'יוספטל'),
    ('בנימינה-גבעת עדה', 'הרחבה (גבעת עדה)',   'גבעת עדה-הרחבה'),
    ('קיסריה', 'שכונה 2',  '2 - החורש'),    ('קיסריה', 'שכונה 2',  'החורש'),
    ('קיסריה', 'שכונה 3',  '3 - הצמרות'),   ('קיסריה', 'שכונה 3',  'הצמרות'),
    ('קיסריה', 'שכונה 4',  '4 - ההדרים'),   ('קיסריה', 'שכונה 4',  'ההדרים'),
    ('קיסריה', 'שכונה 5',  '5 - הפרחים'),   ('קיסריה', 'שכונה 5',  'הפרחים'),
    ('קיסריה', 'שכונה 8',  '8 - הביכורים'), ('קיסריה', 'שכונה 8',  'הביכורים'),
    ('קיסריה', 'שכונה 9',  '9 - העדי'),     ('קיסריה', 'שכונה 9',  'העדי'),
    ('קיסריה', 'שכונה 10', '10 - המעוף'),   ('קיסריה', 'שכונה 10', 'המעוף'),
    ('קיסריה', 'שכונה 12', '12'),
    ('קיסריה', 'שכונה 13', '13 - הרקיע'),   ('קיסריה', 'שכונה 13', 'הרקיע')
  ) as v(city, hood, alias)
  join public.cities c on c.name_key = public.city_name_key(v.city)
  join public.neighborhoods n on n.city_id = c.id and n.name = v.hood
on conflict (neighborhood_id, alias_key) do nothing;

insert into public.city_aliases (city_id, alias)
select c.id, 'זיכרון יעקב'
  from public.cities c
 where c.name_key = public.city_name_key('זכרון יעקב') and c.active
   and not exists (select 1 from public.cities x where x.name_key = public.city_name_key('זיכרון יעקב'))
on conflict (alias_key) do nothing;

do $$
declare v_n integer;
begin
  select count(*) into v_n
    from public.neighborhood_aliases a
    join public.neighborhoods n on n.id = a.neighborhood_id
    join public.cities c on c.id = n.city_id
   where c.market_slug = 'hadera';
  raise notice 'כינויי שכונה בשוק חדרה אחרי המיגרציה: %', v_n;
  if v_n < 20 then
    raise warning 'צפויים לפחות 23 כינויים בשוק חדרה; נמצאו % - שכונה ששמה השתנה בייבוא?', v_n;
  end if;
end $$;
