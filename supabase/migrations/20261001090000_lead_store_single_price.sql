-- ============================================================================
-- חנות הלידים — מחיר אחיד
--
-- שלושת המדפים (מוכרים/קונים מ-RSS, מחפשי דירה, משכנתאות) הפכו למדף אחד
-- בממשק: "חנות הלידים". מחיר אחד לכל ליד בחנות — ₪50 — כדי שהבחירה בין
-- המגירות תהיה על איכות הליד ולא על תג המחיר.
--
-- ‏rss_lead_price ו-mortgage_lead_price כבר עמדו על 50; ‏saved_search_lead_price
-- עמד על 60 ויורד לכאן. שלושתם נכתבים במפורש כדי שהערך בפרויקט יהיה מה
-- שהקוד מציג, גם אם מישהו שינה אותו ידנית בעבר.
--
-- ההיסטוריה אינה נוגעת: amount ברכישות שכבר נרשמו נשמר כפי שחויב בפועל
-- (ראו rss_lead_purchases ואחיותיה), ולכן שינוי המחיר כאן אינו משכתב חיוב
-- שכבר קרה.
-- ============================================================================

insert into public.pricing_config (key, value, description) values
  ('rss_lead_price', 50,
   '₪ לרכישת ליד מוכר/קונה בחנות הלידים (נאסף ממקורות RSS)'),
  ('saved_search_lead_price', 50,
   '₪ לרכישת ליד מחפש/ת דירה בחנות הלידים (הסוכן החכם)'),
  ('mortgage_lead_price', 50,
   '₪ לרכישת ליד ייעוץ משכנתאות בחנות הלידים (מחשבון המשכנתא)')
on conflict (key) do update
  set value       = excluded.value,
      description = excluded.description;
