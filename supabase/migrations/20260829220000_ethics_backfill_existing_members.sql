-- ============================================================================
-- החלת תו האיכות על הסוכנים והמשרדים הקיימים (grandfathering)
--
-- תו האיכות עלה לאוויר כשבמערכת כבר היו סוכנים ומשרדים פעילים. בלי הצעד הזה
-- כולם היו מוצגים בלי תו עד שכל אחד ואחת ייכנסו ל-CRM ויאשרו — כלומר האתר
-- כולו היה נראה כאילו אף אחד לא עומד בתקן.
--
-- ‏החלטה מודעת של הנהלת הפלטפורמה: מי שכבר היה במערכת ביום העלייה לאוויר
-- נחשב כמי שאישר את הקוד. מכאן והלאה האישור נחתם אישית — בפתיחת משרד
-- (‏agency-signup / create-own-agency) או בכניסה הראשונה ל-CRM עבור סוכן/ת
-- שמנהל/ת המשרד הוסיף/ה. הקובץ הזה הוא התיעוד המתוארך של ההחלטה.
--
-- שתי הגנות שהופכות אותו לבטוח גם אם יורץ שוב:
--
--   1. ‏‎where ethics_code_accepted_at is null‎ — לא דורס אישור אמיתי שכבר ניתן.
--   2. ‏‎where created_at < '2026-08-29 21:00:00+00'‎ — חסם קשיח על התאריך.
--      בלי זה, הרצה חוזרת של המיגרציות בעוד חצי שנה הייתה מחתימה בשקט כל
--      סוכן/ת חדש/ה שטרם אישר/ה — בדיוק מה שהמנגנון הזה נועד למנוע.
--
-- העדכון רץ כ-service_role (מיגרציה), ולכן הטריגרים מעבירים אותו כמות שהוא
-- והתאריך הנכתב הוא זה שנשמר.
-- ============================================================================

update public.agency_members
   set ethics_code_accepted_at = now(),
       ethics_code_version     = '2026-08'
 where ethics_code_accepted_at is null
   and ethics_badge_revoked_at is null
   and created_at < timestamptz '2026-08-29 21:00:00+00';

update public.agencies
   set ethics_code_accepted_at = now(),
       ethics_code_version     = '2026-08'
 where ethics_code_accepted_at is null
   and ethics_badge_revoked_at is null
   and created_at < timestamptz '2026-08-29 21:00:00+00';
