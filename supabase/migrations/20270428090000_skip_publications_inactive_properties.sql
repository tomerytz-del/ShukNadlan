-- ===========================================================================
-- תור הפרסום לרשתות: שורה של נכס שאינו פעיל עוד יוצאת מהתור כ-`skipped`
--
-- ‏`pending_property_publications` בוחרת רק `p.status = 'active'`, ולכן שורה
-- `pending` של נכס שנמכר או ירד מהאוויר אינה נבחרת לעולם - היא יושבת בתור
-- עם `attempts = 0` ונספרת בממצא "ממתין לתנאי מקדים: פרסום לרשתות" של
-- הסוכן התפעולי. ב-12.10.2026 היו שתיים כאלה (נכס אחד שנמכר, בשני הערוצים).
--
-- ‏**מה לא נוגעים בו, ובכוונה:**
--   * שורה של נכס **פעיל בלי תמונה** נשארת `pending`. זו ההמתנה המכוונת של
--     ‏`20261025090000_publish_when_image_arrives`: הפוסט יוצא 20 דקות אחרי
--     התמונה הראשונה. ‏`skipped` אינו מוחיה, ולכן סימון שלה היה מחזיר בדיוק
--     את המלכודת שהמיגרציה ההיא ביטלה - סוכן/ת מעלה תמונות ושום דבר לא קורה.
--   * שורה של נכס **פעיל עם תמונה** שממתינה לתורה בתקרה היומית
--     (‏`*_autopost_daily_cap`) - זו מדיניות קצב, והיא תצא בתורה.
--   * שורה שיש לה `post_id` או `attempts > 0` - ייתכן שפוסט עלה, ולפי
--     ‏`docs/facebook-auto-publish.md` כישלון אינו הוכחה שלא פורסם.
--
-- ‏`last_error` נושא את הסיבה, כדי שהיומן יגיד למה השורה יצאה בלי פוסט.
-- אידמפוטנטית: הרצה שנייה אינה מוצאת שורות.
-- ===========================================================================

update public.property_publications pub
   set status     = 'skipped',
       last_error = '[inactive-property] הנכס אינו פעיל - יצא מהתור בלי פרסום (20270428090000)'
  from public.properties p
 where p.id = pub.property_id
   and pub.status = 'pending'
   and p.status <> 'active'
   and pub.post_id is null
   and coalesce(pub.attempts, 0) = 0;
