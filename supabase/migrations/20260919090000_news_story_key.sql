-- ============================================================================
-- ‏story_key — מניעת כפילויות ברמת האירוע, לא ברמת הכתובת
--
-- הבעיה שהתגלתה בהרצה הראשונה: הורדת הריבית של בנק ישראל הופיעה ברצועה
-- ארבע פעמים, מארבעה אתרים שסיקרו את אותו אירוע:
--
--   "בשורה ללווים: בנק ישראל מוריד את הריבית ברבע אחוז"
--   "בפעם השלישית ברצף: הריבית ירדה ב-0.25%, המשכנתאות יוזלו"
--   "הריבית ירדה - בכמה יתכווץ החזר המשכנתא שלכם?"
--   "בהובלת הנדל\"ן: נעילה חיובית בבורסה אחרי הפחתת הריבית"
--
-- מניעת הכפילויות הקיימת עובדת על ‎source_url‎, וארבע כתבות באתרים שונים הן
-- ארבע כתובות שונות — ברמת ה-URL אין שום דרך לדעת שזה אותו סיפור. גם
-- השוואת טקסט לא עוזרת: "מוריד" / "ירדה" / "הפחתת" הן אותה מילה בעברית
-- ובנטיות שונות, וסף דמיון שיתפוס אותן יתפוס גם ידיעות שאינן קשורות.
--
-- הפתרון: ‏Claude ממילא קורא כל ידיעה, ולכן הוא גם מחזיר מזהה מנורמל של
-- *האירוע* בפורמט ‎נושא|אירוע|תקופה‎ (למשל ‎ריבית בנק ישראל|הורדה|2026-09‎).
-- זה שדה נוסף בסכמת הפלט הקיימת — אפס קריאות API נוספות. הדדופליקציה רצה
-- על המפתח הזה, ולכן היא עובדת גם כשהניסוח שונה לגמרי.
--
-- העמודה מתמלאת גם עבור פריטים שנדחו (‎status = 'rejected'‎), כי גם הם
-- חלק מהזיכרון של "איזה סיפורים כבר ראינו".
--
-- הקובץ אידמפוטנטי — אפשר להריץ אותו שוב.
-- ============================================================================

alter table public.news_items
  add column if not exists story_key text;

comment on column public.news_items.story_key is
  'מזהה מנורמל של האירוע בפורמט נושא|אירוע|תקופה, כפי ש-Claude מחזיר אותו. מפתח מניעת הכפילויות בין אתרים שסיקרו את אותו סיפור — להבדיל מ-source_url שמזהה כתבה בודדת.';

-- האינדקס שמשרת את שאילתת הדדופליקציה: המפתחות שנראו בימים האחרונים.
-- חלקי, כי לשורות ישנות מלפני המיגרציה אין מפתח ואין טעם לאנדקס NULL.
create index if not exists news_items_story_key_idx
  on public.news_items(story_key, published_at desc)
  where story_key is not null;
