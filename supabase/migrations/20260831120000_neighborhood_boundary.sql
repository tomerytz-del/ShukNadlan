-- עיגול. בשטח זה לא עבד: שכונה אינה עיגול. רובע יזרעאל הוא מרובע כלוא בין
-- שדרות רבין לנחל חרוד, מרכז העיר צר וארוך לאורך הנשיא וייצמן, וגבעת המורה
-- נפרסת על מדרון. עיגול סביב מרכז המסה שלהן או קוטע להן חצי או גולש הרחק אל
-- השכונות השכנות — ובשני המקרים הוא אומר לגולש/ת דבר שאינו נכון.
--
-- ‏boundary הוא טבעת של נקודות ‎[lat, lng]‎ ב-jsonb. לא PostGIS: הצרכן היחיד הוא
-- ‏L.polygon בדפדפן, שמקבל בדיוק את המבנה הזה, ואין כאן שאילתות מרחביות —
-- הסינון לפי שכונה נעשה ב-neighborhood_id ולא בגאומטריה. הטבעת נשמרת פתוחה
-- (הנקודה האחרונה אינה חוזרת על הראשונה); ‏Leaflet סוגר אותה בעצמו.
--
-- ‏lat/lng/radius_m נשארים כברירת מחדל לשכונה שעדיין לא סומנה — שם עיגול לפחות
-- אומר "בערך כאן" ולא מתיימר לתחום.
--
-- מקור המצולעים: סימון ידני של מנהל/ת הפלטפורמה על מפת החיפוש. אפשר לסמן
-- שכונה נוספת או לתקן קיימת בעמוד ‎neighborhood-boundary.html‎, שמייצר בדיוק
-- את משפט ה-update שלמטה.
-- ============================================================================

alter table public.neighborhoods
  add column if not exists boundary jsonb;

comment on column public.neighborhoods.boundary is
  'טבעת גבול השכונה: מערך של [lat, lng], פתוחה. ריק = המפה נופלת לעיגול לפי lat/lng/radius_m.';

-- טבעת חוקית בלבד: מערך של לפחות שלוש נקודות, כל אחת זוג מספרים. מצולע פגום
-- צריך להיעצר כאן ולא להגיע למפה.
--
-- ‏jsonpath ולא תת-שאילתה: ‏Postgres אוסר subquery ב-check. ‏strict חיוני —
-- במצב lax המנוע "משטח" מערכים מקוננים, ואז כל זוג [lat,lng] נפרש לשני
-- מספרים והבדיקה נכשלת דווקא על טבעת תקינה.
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.neighborhoods'::regclass
      and conname = 'neighborhoods_boundary_shape'
  ) then
    alter table public.neighborhoods
      add constraint neighborhoods_boundary_shape check (
        boundary is null or (
          jsonb_typeof(boundary) = 'array'
          and jsonb_array_length(boundary) >= 3
          -- כל איבר הוא מערך בגודל 2...
          and not (boundary @? 'strict $[*] ? (@.type() != "array" || @.size() != 2)')
          -- ...ושני האיברים שבו מספרים
          and not (boundary @? 'strict $[*][*] ? (@.type() != "number")')
        )
      );
  end if;
end $$;

