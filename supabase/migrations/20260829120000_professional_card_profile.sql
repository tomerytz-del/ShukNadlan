-- ============================================================================
-- כרטיסיית בעל-מקצוע — שם עסק ותמונת פרופיל
--
-- כרטיסיות "בעלי מקצוע נבחרים" בדף הבית עברו לעיצוב של אריח המתווך/ת:
-- תמונה שממלאת את כל הכרטיס, ומתחתיה שם בעל/ת המקצוע ושם העסק. שתי
-- השורות האלה דרשו הפרדה של מה שהיה עד היום שדה אחד:
--
--   * advertiser_name — נשאר שם בעל/ת המקצוע (השורה הראשונה באריח).
--   * business_name   — חדש: שם העסק (השורה השנייה). NULL עבור מי שנרשם
--                       לפני השינוי, ואז התצוגה נופלת לתחום העיסוק.
--   * creative_url    — קיים כבר בטבלה ומשמש עכשיו כתמונת הפרופיל של
--                       הכרטיסייה (עבור באנרים הוא ממשיך להיות הקריאייטיב).
--
-- אידמפוטנטי — אפשר להריץ שוב.
-- ============================================================================

alter table public.ad_placements
  add column if not exists business_name text;

comment on column public.ad_placements.business_name is
  'שם העסק של בעל/ת המקצוע — השורה השנייה בכרטיסיית "בעלי מקצוע נבחרים". NULL = נופל לתחום העיסוק בתצוגה.';

comment on column public.ad_placements.creative_url is
  'כתובת התמונה של הפרסום. בכרטיסיית בעל-מקצוע זו תמונת הפרופיל שממלאת את האריח; בבאנר — הקריאייטיב.';
