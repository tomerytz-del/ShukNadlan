-- שוק רמת גן וגבעתיים: שכונות שאינן ב-GovMap עם מצולע משוער, וכינוי אחד ביהוד-מונוסון
--
-- אחרי ייבוא השכונות 62% מעסקאות רמת גן עם שם שכונה אינן מקושרות לשכונה
-- (1,009 מ-1,623), בראשן "רמת אפעל" (419 עסקאות, 78 עם פין). הצלבה מול
-- market_deals_official (21.11.2026, .claude/skills/new-market/hoods_crosscheck.sql)
-- והכלי scripts/hood_polygons.py (נבדק על חדרה: אותם 19 מצולעים ואותם כינויים
-- כמו #1364) נתנו:
--
--   * 11 שכונות עם מצולע משוער מפיני העסקאות: 10 ברמת גן - רמת אפעל, תל יהודה,
--     כפר אז"ר, אזור הבילוים, שיכון המזרחי, הגפן, ותיקים, מרום נווה, תל השומר,
--     תל בנימין - ואחת באור יהודה - שפרינצק. אפס חפיפה מול מצולע של GovMap או מצולע
--     משוער אחר, ושום קודקוד אינו על קו של מצולע אחר (המרחק המזערי 3.1 מ')
--     - neighborhood_for_city_point מחזירה null לנקודה בשני מצולעים.
--   * כינוי אחד: "רסקו" ביהוד-מונוסון (114 עסקאות, 100% מהפינים) = מכב"י.
--
-- ומה לא נכנס, בכוונה:
--   * "מרכז העיר א/ב/ג" (172 עסקאות) הם תת-אזורים של רשות המיסים ש-80% עד
--     100% מהפינים שלהם בתוך שכונות של GovMap (חשמונאים, יהלום, בן גוריון).
--     מצולע משוער היה רק הפערים ביניהן. עסקה עם פין משויכת בכל מקרה לשכונת
--     GovMap לפי הנקודה.
--   * "שיכון ממשלתי" באור יהודה (22 מ-24 פינים ב"'סקיה א", 92%): מתחת לסף
--     הכינוי (95%), ונשאר להכרעה ידנית.
--   * "אזור תעשיה" ביהוד-מונוסון: הפינים מפוזרים על ארבע שכונות.
--
-- הערה על "שפרינצק": 8 פינים בלבד, ביטחון נמוך. אם יתברר שגוי, מוחקים את
-- השורה (ייבוא עתידי לא ידרוס, כי היא תהיה "קיימת עם גבול").
--
-- מפוצל לארבעה קבצים (120000, 140000, 150000, 160000) כי הטריגר
-- neighborhoods_relink_deals מקשר מחדש את כל עסקאות העיר *לכל שורה* שנכנסת,
-- וברמת גן זה כ-9 שניות לשורה (1,623 עסקאות עם שם שכונה, ‏neighborhood_ids_for
-- בכל אחת). 11 שורות וכינוי בקובץ אחד חצו את שתי הדקות של db push, וההרצה
-- הראשונה (21.11.2026, אחרי #1378) נכשלה בלי להחיל דבר. שלוש שורות בקובץ הן
-- כחצי דקה. אין בזה שינוי במה שנכנס, ואין תלות בין הקבצים.
-- חלק 4 מ-4: תל השומר, תל בנימין, והכינוי רסקו
--
insert into public.neighborhoods (city, name, city_id, lat, lng, is_industrial, boundary)
select v.city, v.name, c.id, v.lat, v.lng, v.is_industrial, v.boundary
  from (values
  ('רמת גן', 'תל השומר', 32.045681, 34.846654, false, 23, '[[32.049234,34.845917],[32.046073,34.849247],[32.045799,34.849413],[32.045491,34.849398],[32.042312,34.848254],[32.044904,34.843903],[32.046142,34.843851],[32.049234,34.845917]]'::jsonb),
  ('רמת גן', 'תל בנימין', 32.084837, 34.807170, false, 10, '[[32.083953,34.807842],[32.08391,34.807828],[32.082405,34.808335],[32.082272,34.808281],[32.082222,34.808224],[32.08202,34.808176],[32.081482,34.808194],[32.08138,34.808041],[32.084498,34.805179],[32.085314,34.804815],[32.085593,34.804516],[32.087576,34.806268],[32.08621,34.807223],[32.085969,34.808212],[32.086185,34.808498],[32.086277,34.809192],[32.085324,34.810278],[32.08454,34.809362],[32.083953,34.807842]]'::jsonb)
  ) as v(city, name, lat, lng, is_industrial, pins, boundary)
  join public.cities c on c.name_key = public.city_name_key(v.city) and c.active
 where not exists (
   select 1 from public.neighborhoods n
    where n.city_id = c.id
      and public.neighborhood_name_key(n.name) = public.neighborhood_name_key(v.name))
on conflict (city, name) do nothing;

insert into public.neighborhood_aliases (neighborhood_id, alias, shared, note)
select n.id, v.alias, false, 'השם במאגר רשות המיסים: כל הפינים בתוך המצולע הזה'
  from (values
    ('יהוד-מונוסון', 'מכב"י', 'רסקו')
  ) as v(city, hood, alias)
  join public.cities c on c.name_key = public.city_name_key(v.city)
  join public.neighborhoods n on n.city_id = c.id and n.name = v.hood
on conflict (neighborhood_id, alias_key) do nothing;
