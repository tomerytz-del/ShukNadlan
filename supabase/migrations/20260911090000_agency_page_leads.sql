-- ============================================================================
-- לידים שנוצרו בדף המשרד
--
-- ‏agency.html מציג מעכשיו שני כלים שמייצרים לידים בתוך הדף של משרד מסוים:
--
--   1. **באנר הערכת השווי** — אותו רכיב ואותו אשף בן שלושת השלבים שיושבים
--      בדף הבית. ‏lead_type: owner_inbound.
--   2. **מחשבון התשואה** — נפתח מרכיב מצומצם, ובסופו CTA להשארת פרטים.
--      מי שממלא/ת אותו מחפש/ת דווקא *לקנות*, ולכן ‏lead_type:
--      property_inquiry ולא owner_inbound.
--
-- הליד שנוצר בשניהם אינו שייך לפלטפורמה אלא למשרד שבדף: הגולש/ת בחר/ה
-- להשאיר פרטים *שם*, ולא בכיכר הראשית.
--
-- לכן ‏owner-lead-intake מתנהג איתו אחרת לגמרי:
--
--   * **בלי רוטציה.** מנגנון ההתאמה (שכונה → סוג נכס → תור) נעקף כולו.
--     הליד משויך למנהל/ת המשרד; משרד בלי מנהל/ת פעיל/ה נופל לסוכן/ת
--     הראשון/ה, כדי שהפנייה לא תישאר בתיבה שאיש לא פותח.
--   * **בלי מחיר.** הליד נכנס כבר במצב `unlocked`, כלומר שם וטלפון גלויים
--     מהרגע הראשון. אין מה לרכוש, אין מכסה חינמית לנצל, ו-`claim_lead` לא
--     נקראת עליו בכלל. זו ההבטחה למנהלי המשרדים: מה שהדף שלכם מייצר —
--     שלכם.
--   * **בלי בלעדיות.** ‏owner_lead_exclusivity_hours לא רלוונטי כשאין סוכן/ת
--     שני/ה בתור.
--
-- מה שהמיגרציה הזו מוסיפה הוא הדבר היחיד שחסר במסד: עמודה שאומרת מאיפה
-- הליד הגיע. בלעדיה אי אפשר להבדיל בדוחות בין ליד של הפלטפורמה לליד שהמשרד
-- הביא לעצמו — ושתי השורות נראות זהות לגמרי, כי כל שאר השדות אכן זהים.
--
-- העמודה היא טקסט חופשי ולא enum בכוונה: מקורות חדשים (קמפיין, QR על שלט,
-- דף נחיתה של סוכן/ת) ייכנסו בלי DDL, והצריכה היחידה שלה היא סינון ודיווח.
-- ‏null = לידים שנוצרו לפני המיגרציה, ומקורם הוא המסלול הרגיל.
--
-- הקובץ אידמפוטנטי.
-- ============================================================================

alter table public.leads
  add column if not exists source text;

comment on column public.leads.source is
  'מאיפה הליד הגיע. ''agency_page'' = אחד הכלים בדף המשרד — הערכת שווי או מחשבון תשואה (משויך למנהל/ת המשרד ונפתח מיד, ללא עלות). null = המסלול הרגיל של הפלטפורמה.';

-- אינדקס חלקי: השאילתה היחידה שנשענת על העמודה היא "מה הדף של המשרד הזה
-- הביא", כלומר תמיד עם source לא-null. אינדקס מלא היה מכסה בעיקר שורות null.
create index if not exists leads_agency_source_idx
  on public.leads (agency_id, created_at desc)
  where source is not null;
