-- ============================================================================
-- הפעמון: הרשאת המחיקה של ההתראות נכנסת לצינור
--
-- ## מה נכנס לדפדפן
--
-- כפתור "נקה נקראו" בכותרת הפעמון מוחק את ההתראות שכבר נקראו. עד היום
-- לא הייתה לפעמון שום דרך להיפטר משורה: קריאה הפכה את read ל-true, השורה
-- איבדה את הרקע הוורוד, ונשארה. אחרי 168 שורות (91 מהן לא נקראו) הפאנל
-- כבר לא היה רשימת משימות אלא ארכיון.
--
-- ## למה יש כאן בכלל מיגרציה
--
-- ה-policy שהמחיקה נשענת עליו — "agent deletes own notifications" — **קיים
-- בפרודקשן ואינו קיים באף קובץ בריפו.** טבלת notifications נולדה לפני
-- תיקיית המיגרציות, וההרשאה הזו מעולם לא תועדה. המיגרציה הזו מצהירה עליה
-- באותה הגדרה בדיוק, ולכן היא no-op מול המסד הקיים.
--
-- ## למה זה לא "ניקיון תיעוד" אלא תנאי לתקינות
--
-- ‏DELETE שאין לו policy תואם ב-RLS **אינו מחזיר שגיאה**. הוא מוחק אפס
-- שורות ומדווח הצלחה. כלומר מסד שייבנה מחדש מהמיגרציות בלבד — סביבת בדיקה,
-- שחזור, פרויקט חדש — יקבל כפתור שנראה עובד, לא מתלונן, ולא מוחק דבר.
-- זה בדיוק סוג הכשל שקשה לאתר: אין שגיאה בקונסול, אין שורה אדומה ביומן,
-- רק רשימה שמסרבת להתקצר.
--
-- ההגנה בצד הדפדפן קיימת גם היא — crm.html משווה את מספר השורות שחזרו
-- מ-delete().select() למה שהוצג באישור — אבל הגנה שמדווחת על תקלה אינה
-- תחליף להרשאה שקיימת.
--
-- הקובץ אידמפוטנטי.
-- ============================================================================

-- ה-policy מגודר ל-current_agent_id() בדיוק כמו אחיו לקריאה ולעדכון: כל
-- סוכן/ת נוגע/ת אך ורק בהתראות של עצמו/ה. אין כאן הרחבת גישה — הסינון
-- ל-read=true נעשה בדפדפן, והמסד לא מבחין בין מחיקת התראה שנקראה לאחרת,
-- כפי שהיה עד היום.
drop policy if exists "agent deletes own notifications" on public.notifications;
create policy "agent deletes own notifications"
  on public.notifications for delete
  using (agent_id = public.current_agent_id());
