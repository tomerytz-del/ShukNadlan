-- ============================================================================
-- "הרובע" / "רובע" - רובע יזרעאל בעפולה
--
-- בעפולה אומרים "ברובע" ומתכוונים לרובע יזרעאל. אין במאגר שכונה אחרת
-- שנקראת "רובע" (נבדק 5.10.2026), ולכן הכינוי אינו דו-משמעי.
--
-- ההכרעה (מנהל הפלטפורמה, 5.10.2026): חיפוש "ברובע" בעפולה הוא חיפוש
-- ברובע יזרעאל. ‏`search_properties` בבוט הציבורי קורא את הכינויים מכאן,
-- ו"ברובע" מכיל את הכינוי "רובע".
--
-- הטריגר `neighborhood_aliases_relink_deals` משייך מחדש את עסקאות העיר
-- מעצמו, ולכן אין כאן update. ‏`on conflict do nothing` - בטוחה להרצה חוזרת.
-- ============================================================================

insert into public.neighborhood_aliases (neighborhood_id, alias, shared, note)
select n.id, v.alias, false, v.note
  from (values
    ('רובע',  '"ברובע" בעפולה = רובע יזרעאל (הכרעת מנהל הפלטפורמה, 5.10.2026)'),
    ('הרובע', '"ברובע" בעפולה = רובע יזרעאל (הכרעת מנהל הפלטפורמה, 5.10.2026)')
  ) as v(alias, note)
  join public.cities c on c.name = 'עפולה'
  join public.neighborhoods n on n.city_id = c.id and n.name = 'רובע יזרעאל'
on conflict (neighborhood_id, alias_key) do nothing;
