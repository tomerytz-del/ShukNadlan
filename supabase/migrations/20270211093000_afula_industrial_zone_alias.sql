-- ============================================================================
-- "אזור תעשיה ומסחר" - כינוי של "אזור התעשייה" בעפולה
--
-- במאגר רשות המיסים 31 עסקאות בעפולה רשומות תחת "אזור תעשיה ומסחר", ואין
-- לנו שכונה בשם הזה, ולכן הן נשארו בלי שיוך (`neighborhood_ids` null). כל
-- הפינים שלהן נופלים במצולע אחד: "אזור התעשייה" (נבדק 4.10.2026 בשאילתת
-- "שמות שלא הותאמו" שבסקיל new-market).
--
-- בחיפוש העסקאות לפי שכונה הן כבר נכללו לפי מיקום (20270211092000). הכינוי
-- מעביר אותן לשיוך לפי שם, ובכך גם לשכבת השכונה בדוח ה-CMA ולסוכן התפעולי
-- (`market_deal_hoods_unmatched`).
--
-- הכרעת מנהל הפלטפורמה, 4.10.2026. הטריגר `neighborhood_aliases_relink_deals`
-- משייך מחדש את עסקאות העיר מעצמו. ‏`on conflict do nothing` - בטוח להרצה חוזרת.
-- ============================================================================

insert into public.neighborhood_aliases (neighborhood_id, alias, shared, note)
select n.id, 'אזור תעשיה ומסחר', false,
       'השם במאגר רשות המיסים; כל הפינים במצולע של אזור התעשייה (הכרעת מנהל הפלטפורמה, 4.10.2026)'
  from public.cities c
  join public.neighborhoods n on n.city_id = c.id and n.name = 'אזור התעשייה'
 where c.name = 'עפולה'
on conflict (neighborhood_id, alias_key) do nothing;
