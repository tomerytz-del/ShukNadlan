-- ============================================================================
-- הודעה למנהל/ת המשרד על בלעדיות חדשה
--
-- ‏בלעדיות היא התחייבות של המשרד, לא של הסוכן/ת בלבד: היא כובלת את הנכס
-- לתקופה, מחייבת פעולות שיווק בפועל, ומטילה על המשרד חשיפה אם הן לא בוצעו.
-- לכן ברגע שהיא נחתמת יוצאת הודעה למנהל/ת המשרד. שאר סוגי ההסכם אינם
-- מפעילים אותה — הזמנת תיווך רגילה היא עניין של הסוכן/ת מול הלקוח/ה.
--
-- ‏העמודה כאן היא מה שהופך את ההודעה לחד-פעמית. בלעדיה כל שליחה חוזרת של
-- העותק החתום (‏action=finalize, כפתור "שליחת עותק שוב") הייתה מודיעה
-- למנהל/ת שוב על אותה בלעדיות.
--
-- הקובץ אידמפוטנטי.
-- ============================================================================

alter table public.agreements
  add column if not exists manager_notified_at timestamptz;

comment on column public.agreements.manager_notified_at is
  'מועד ההודעה למנהל/ת המשרד על בלעדיות חדשה. לא null = כבר הודענו, ושליחה חוזרת של העותק החתום לא תודיע שוב.';
