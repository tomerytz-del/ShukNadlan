-- ============================================================================
-- רדיוס הבסיס של דוח ה-CMA עולה מ-500 מ' לקילומטר
--
-- החלטת מנהל/ת הפלטפורמה, אחרי בדיקה על שני נכסים אמיתיים שבהם 500 מ'
-- לא החזירו די בני השוואה.
--
-- הרדיוס מתרחב ממילא כשאין די עסקאות - `[r, r*2, r*3, r*4, r*6]` - ולכן
-- מה שמשתנה כאן אינו **עד לאן** אפשר להגיע אלא **מאיפה מתחילים**:
--
--   היה   500 · 1,000 · 1,500 · 2,000 · 3,000
--   עכשיו 1,000 · 2,000 · 3,000 · 4,000 · 6,000
--
-- ## ההסתייגות, וכדאי שתירשם
--
-- **העדות נאספה כשהמאגר היה כמעט בלי פינים.** בזמן הבדיקה היו 0 עד 21
-- עסקאות עם `lat`/`lng` מתוך 1,046 הניתנות לגאוקוד, ובמצב כזה **שום
-- רדיוס לא היה מחזיר דבר** - לא 500 מ' ולא 6 ק"מ. כלומר מה שנמדד הוא
-- היעדר נתונים ולא היעדר טווח.
--
-- **והמחיר של רדיוס רחב אינו אפס.** בעפולה מחיר למ"ר נע בין כ-9,000
-- בגבעת המורה לכ-15,000 ברובע יזרעאל, ושכונות שלמות יושבות בתוך
-- קילומטר זו מזו. רדיוס בסיס של קילומטר הופך **ערבוב שכונות מברירת
-- מחדל של מצוקה לברירת המחדל הרגילה**, והממוצע נעשה אמיתי פחות ככל
-- שהמדגם גדל.
--
-- לכן שווה למדוד שוב אחרי שכל 1,046 הפינים ייכנסו: אם ב-500 מ' יש די
-- עסקאות, הערך הזה הוא שורה אחת לחזור בה. ‏`radius_meters_used` חוזר
-- בדוח ואומר בכל קריאה באיזה שלב באמת נעצרנו, כלומר התשובה נמדדת ולא
-- משוערת.
--
-- זו שורת תצורה ולא קוד: היא ניתנת לשינוי בלי פריסה, וזו כל הסיבה
-- שהסף הזה חי ב-`pricing_config` מלכתחילה.
-- ============================================================================

update public.pricing_config
   set value = 1000
 where key = 'cma_default_radius_meters';

insert into public.pricing_config (key, value)
values ('cma_default_radius_meters', 1000)
on conflict (key) do nothing;

do $$
declare v_radius numeric;
begin
  select value into v_radius from public.pricing_config
   where key = 'cma_default_radius_meters';
  raise notice 'רדיוס הבסיס של ה-CMA: % מטר (הרחבה עד %)', v_radius, v_radius * 6;
end $$;
