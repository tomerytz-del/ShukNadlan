-- גולשים כותבים "במרכז" או "מרכז עפולה" ומתכוונים לשכונת מרכז העיר. בלי
-- כינוי, "מרכז" נתפס כהתאמה חלקית גם ב"מרכז עפולה עלית" (‏`sales_area` של
-- בית בעפולה עלית), ו"מרכז עפולה" תפס **רק** אותו ולא אף נכס במרכז העיר.
--
-- ההכרעה (מנהל הפלטפורמה, 5.10.2026): "מרכז" בעפולה הוא מרכז העיר.
-- ‏`search_properties` בבוט הציבורי נותן לכינוי מדויק עדיפות על התאמה חלקית,
-- ו"במרכז" / "המרכז" מגיעים אליו אחרי הורדת אות היחס.
--
-- הטריגר `neighborhood_aliases_relink_deals` משייך מחדש את עסקאות העיר
-- מעצמו, ולכן אין כאן update. ‏`on conflict do nothing` - בטוחה להרצה חוזרת.
-- ============================================================================

insert into public.neighborhood_aliases (neighborhood_id, alias, shared, note)
select n.id, v.alias, false, v.note
  from (values
    ('מרכז',       '"מרכז" בעפולה = מרכז העיר (הכרעת מנהל הפלטפורמה, 5.10.2026)'),
    ('מרכז עפולה', '"מרכז" בעפולה = מרכז העיר (הכרעת מנהל הפלטפורמה, 5.10.2026)')
  ) as v(alias, note)
  join public.cities c on c.name = 'עפולה'
  join public.neighborhoods n on n.city_id = c.id and n.name = 'מרכז העיר'
on conflict (neighborhood_id, alias_key) do nothing;
