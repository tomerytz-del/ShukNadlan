-- ============================================================================
-- כתובת המשרד
--
-- ל-agencies היו עד היום שם, מוטו, לוגו, צבעים ואזורי פעילות — אבל לא כתובת.
-- ‏"אזורי פעילות" עונים על "איפה אתם עובדים"; כתובת עונה על "לאן אני בא/ה",
-- וזו שאלה אחרת לגמרי: מי שכבר החליט/ה לפנות למשרד רוצה לדעת אם אפשר לקפוץ
-- אליו, ומשרד בלי כתובת נראה כמו מי שאין לו אחת.
--
-- בדף המשרד היא מוצגת במקטע יצירת הקשר, לצד מנהל/ת המשרד, ומקושרת ל-Google
-- Maps. במסך המיתוג ב-CRM מנהל/ת המשרד מזין/ה אותה.
--
-- שדה טקסט חופשי ולא רחוב/מספר/עיר נפרדים: משרדים יושבים גם בקניונים
-- ובמרכזים מסחריים ("קניון עפולה, קומה 2, חנות 214"), וחלוקה לשדות הייתה
-- מכריחה אותם למלא טופס שלא מתאים לכתובת שלהם. 160 תווים — מספיק לכתובת
-- מלאה עם קומה ומספר, ולא מספיק לפסקה.
--
-- הקובץ אידמפוטנטי.
-- ============================================================================

alter table public.agencies
  add column if not exists address text;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'agencies_address_length_check') then
    alter table public.agencies
      add constraint agencies_address_length_check
      check (address is null or char_length(address) <= 160);
  end if;
end $$;

comment on column public.agencies.address is
  'כתובת המשרד כטקסט חופשי (עד 160 תווים), כפי שמנהל/ת המשרד הזין/ה במסך המיתוג. מוצגת במקטע יצירת הקשר בדף המשרד ומקושרת למפה. null = לא הוזנה, והשורה בדף לא מוצגת.';
