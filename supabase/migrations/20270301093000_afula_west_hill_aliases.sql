-- ============================================================================
-- "המערבית" = השכונה הצפון מערבית, "הגבעה" = גבעת המורה (עפולה)
--
-- שני כינויים מקומיים שגולשים כותבים לגבריאלה: "דירה במערבית", "בגבעה".
-- בלי כינוי, "גבעה" אינה מופיעה בתוך "גבעת המורה" (ת ולא ה), ו"מערבית"
-- נתפסה רק כהתאמה חלקית.
--
-- ההכרעה (מנהל הפלטפורמה, 5.10.2026). ‏`search_properties` בבוט הציבורי
-- מוריד "ב"/"ה" בתחילת השם לפני ההשוואה לכינוי, ולכן "במערבית" ו"בגבעה"
-- מגיעים לכאן. כינוי מדויק גובר על התאמה חלקית - "המערבית" אינה מערב העיר
-- (שיכון גאולים).
--
-- הטריגר `neighborhood_aliases_relink_deals` משייך מחדש את עסקאות העיר
-- מעצמו, ולכן אין כאן update. ‏`on conflict do nothing` - בטוחה להרצה חוזרת.
-- ============================================================================

insert into public.neighborhood_aliases (neighborhood_id, alias, shared, note)
select n.id, v.alias, false, v.note
  from (values
    ('השכונה הצפון מערבית', 'המערבית',  '"המערבית" בעפולה = השכונה הצפון מערבית (הכרעת מנהל הפלטפורמה, 5.10.2026)'),
    ('השכונה הצפון מערבית', 'מערבית',   '"המערבית" בעפולה = השכונה הצפון מערבית (הכרעת מנהל הפלטפורמה, 5.10.2026)'),
    ('גבעת המורה',          'הגבעה',    '"בגבעה" בעפולה = גבעת המורה (הכרעת מנהל הפלטפורמה, 5.10.2026)'),
    ('גבעת המורה',          'גבעה',     '"בגבעה" בעפולה = גבעת המורה (הכרעת מנהל הפלטפורמה, 5.10.2026)')
  ) as v(hood, alias, note)
  join public.cities c on c.name = 'עפולה'
  join public.neighborhoods n on n.city_id = c.id and n.name = v.hood
on conflict (neighborhood_id, alias_key) do nothing;
