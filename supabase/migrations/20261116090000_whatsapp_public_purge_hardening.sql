-- ============================================================================
-- העוזר הציבורי: סגירת ההרשאה על פונקציית הניקוי, והשלמת המחיקה
--
-- שני תיקונים למיגרציה 20261115090000, שכבר הוחלה. **הם כאן ולא שם** מסיבה
-- אחת: ‏`20261115090000` רשומה ב-`schema_migrations`, ולכן עריכה של הקובץ
-- ההוא לא הייתה רצה לעולם על המסד הקיים. קובץ מיגרציה שכבר הוחל הוא תיעוד
-- של מה שרץ, לא מקום לתקן בו.
--
-- ---------------------------------------------------------------------------
-- ‏1. ההרשאה — הפרה של כלל שסגרנו בעצמנו לפני ארבעה ימים
-- ---------------------------------------------------------------------------
--
-- ‏`purge_whatsapp_public_conversations()` נוצרה כ-SECURITY DEFINER בלי
-- ‏`revoke`. ברירת המחדל של Postgres היא EXECUTE ל-PUBLIC, ו-PostgREST חושף
-- כל פונקציה ב-`/rest/v1/rpc/<שם>` — כך שה-ACL בפועל היה:
--
--   =X/postgres | anon=X/postgres | authenticated=X/postgres
--
-- כלומר פונקציה שמוחקת שורות, קריאה לכל מי שמחזיק את המפתח הציבורי — והוא
-- יושב גלוי בקוד המקור של כל דף, כי זה תפקידו.
--
-- **הרדיוס כאן קטן, וראוי לומר זאת במדויק:** לפונקציה אין פרמטרים, ותנאי
-- ה-WHERE שלה קבועים בקוד. מי שיקרא לה יגרום לניקוי היומי לרוץ מוקדם —
-- ולא יוכל למחוק שיחה טרייה, ליד, או שורה כלשהי שאינה בת 30 יום. זו אינה
-- דליפה ואינה מחיקה שרירותית.
--
-- ולמרות זאת היא נסגרת, כי הכלל אינו "לסגור מה שמסוכן" אלא "להחליט על
-- ההרשאות במפורש": ‏20261112090000 סגרה בדיוק את הדפוס הזה בחמש פונקציות,
-- והסקיל `new-migration` מחייב אותו בכל פונקציה חדשה. פונקציה שנקראת רק
-- ממשימת pg_cron אינה צריכה שאיש אחר יוכל לקרוא לה.
--
-- ---------------------------------------------------------------------------
-- ‏2. המחיקה לא הייתה שלמה
-- ---------------------------------------------------------------------------
--
-- ‏`privacy.html` מבטיח לגולש/ת שתוכן השיחה עם העוזר נמחק אחרי 30 יום.
-- הפונקציה מחקה רק את `whatsapp_public_conversations`, בעוד שגוף כל הודעה
-- נכנסת — כולל **תמלול של הקלטות קוליות** — נשמר גם ב-
-- `whatsapp_messages.body`, ושם הוא היה נשאר לנצח.
--
-- הבטחת פרטיות שאינה מדויקת גרועה מהיעדר הבטחה, ולכן הפונקציה מאפסת עכשיו
-- גם את `body` ואת `media_url` של הודעות ציבוריות ישנות.
--
-- **השורה נשארת, התוכן יורד.** ‏`whatsapp_messages` היא גם מנגנון ה-de-dup
-- מול משלוחים חוזרים של Meta (‏`wa_message_id`), גם הבסיס לבלם הקצב של הבוט
-- הציבורי, וגם מה שהבדיקה החודשית ב-`whatsapp_public_bot_check.yml` סופרת.
-- מחיקת השורות הייתה שוברת את שלושתם; איפוס התוכן משאיר את כולם שלמים
-- ומותיר מאחור מטא-דאטה בלי גוף.
--
-- ‏`agent_id is null` = פונה ציבורי. שיחות של סוכנים הן נתוני עבודה של
-- המשרד, והן אינן בהבטחה הזו.
-- ============================================================================

create or replace function public.purge_whatsapp_public_conversations()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_deleted integer;
begin
  delete from public.whatsapp_public_conversations
   where last_message_at < now() - interval '30 days';
  get diagnostics v_deleted = row_count;

  update public.whatsapp_messages
     set body = null,
         media_url = null
   where agent_id is null
     and created_at < now() - interval '30 days'
     and (body is not null or media_url is not null);

  return v_deleted;
end;
$$;

comment on function public.purge_whatsapp_public_conversations() is
  'מוחקת שיחות ציבוריות ששקטו 30 יום, ומאפסת את גוף ההודעות הציבוריות הישנות ב-whatsapp_messages (השורה נשארת — היא ה-de-dup ובסיס הספירה). רצה ב-pg_cron פעם ביום.';

-- ‏revoke על הרשאה שכבר בוטלה אינה שגיאה, ו-grant חוזר ל-service_role אינו
-- משנה דבר — כלומר הבלוק אידמפוטנטי ובטוח בהרצה חוזרת.
revoke all on function public.purge_whatsapp_public_conversations()
  from public, anon, authenticated;
grant execute on function public.purge_whatsapp_public_conversations()
  to service_role;

-- משימת ה-pg_cron רצה כבעלים (postgres), ולכן היא אינה נשענת על ההרשאות
-- שבוטלו כאן וממשיכה לעבוד כרגיל. אין צורך לתזמן אותה מחדש.
