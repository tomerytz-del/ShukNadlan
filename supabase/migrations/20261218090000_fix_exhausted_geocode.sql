-- ============================================================================
-- ארבעה נכסים שמיצו את תור הגאוקוד
--
-- ‏`geocode_attempts >= 3` מוציא נכס מהתור **לצמיתות** (ראו docs/geocoding.md
-- ו-20261107090000_geocode_requeue_not_found). ארבעה נכסים פעילים בעפולה
-- הגיעו לשם עם `address_not_found`, כלומר הם לעולם לא יקבלו פין ולא יופיעו
-- על שום מפה באתר.
--
-- הבדיקה הראתה **שתי תקלות שונות**, ושמות הרחובות הנכונים אומתו מול
-- מנהל/ת הפלטפורמה. אף אחד מהתיקונים אינו ניחוש קואורדינטה.
--
-- ## שם הרחוב היה שגוי (נכס אחד מתוך שניים)
--
--   רום יעל 7  ->  יעל רום 7     (סדר המילים היה הפוך)
--
-- **מאפסים את המונה ולא כותבים פין.** הרחוב קיים ברישום עם
-- `source = 'gis'`, כלומר הוא מגיע משכבת הכתובות של העירייה - ולכן הצינור
-- אמור לפתור אותו בעצמו. זו גם הדרך שמאמתת שהתיקון אמיתי: אם הפין יגיע,
-- השם נכון.
--
-- ‏"יוקה פארק 1" היה אמור להיות כאן גם הוא, ונחסם. ראו ההסבר למטה.
--
-- ## הכתובת תקינה אך אינה בשכבה (שני נכסים)
--
--   היצירה 5 (x2)
--
-- ‏`היצירה` הוא `source = 'legacy'` - הוא **אינו** בשכבה העירונית, ולכן
-- איפוס המונה היה שורף שלושה ניסיונות נוספים ומחזיר אותם לאותו מצב.
--
-- אבל שלושה נכסים אחרים באותה כתובת בדיוק כבר נושאים פין, וכולם על
-- **נקודה אחת** (נבדק: `distinct_pins = 1`). מעתיקים ממנה.
--
-- ‏`having count(distinct ...) = 1` אינו קישוט: אם שלושת המקורות אינם על
-- אותה נקודה, "מאיזה להעתיק" היא שאלה בלי תשובה נכונה, והמיגרציה פשוט
-- לא תעדכן במקום לבחור באקראי.
--
-- **וההשוואה מעוגלת ל-6 ספרות, לא על הטקסט הגולמי.** ‏`lat::text` מדפיס
-- את ה-`double precision` כפי שהוא, ולכן `32.6053163` ו-
-- `32.6053162641914` נראים שם כשתי נקודות שונות - בעוד שבפועל אלה אותם
-- ‏11 מילימטרים. זה קרה בדיוק כאן, ב-`חרוד 1`, והוביל אותי לכתוב בגרסה
-- קודמת שיש שם "שני פינים שונים". אין. שש ספרות עשרוניות הן כ-11 ס"מ,
-- וזו הרזולוציה שבה השאלה "אותה נקודה?" היא שאלה על מיקום ולא על ייצוג.
--
-- ## השכונות
--
-- שלושת הנכסים האלה כבר משויכים ל"אזור התעשייה" ול"רובע יזרעאל" נכון,
-- מ-20261212099000. אין כאן מה לשנות.
--
-- למה מיגרציה ולא עדכון ידני: זו אותה תבנית של שבע ההכרעות האנושיות
-- ב-20261212099000. תיקון נתונים שעובר בצינור אפשר לקרוא, לבקר ולשחזר.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. שם רחוב שגוי -> הצינור פותר בעצמו
-- ---------------------------------------------------------------------------
update public.properties
   set street               = 'יעל רום',
       geocode_attempts     = 0,
       geocode_attempted_at = null,
       geocode_error        = null
 where id = '040a95f4-a064-40bb-8f19-bf3799ef5fa2'
   and street = 'רום יעל';

-- ‏"יוקה פארק 1" (מודעה 1051) **אינו כאן**, וזה ממצא ולא השמטה.
--
-- הניסיון לשנות אותו ל-"חרוד" נחסם בפרודקשן על ידי
-- ‏`properties_guard_duplicate`:
--
--   ERROR: הנכס כבר מפורסם במשרד שלכם על ידי תומר יצחק (מודעה #1049).
--
-- ובדיקה הראתה שאלה **אינן** כפילות אלא שתי יחידות באותו מתחם תעשייה:
--
--   מודעה 1049 — "יוקה פארק חרוד 1", 500 מ"ר, 26,000 ש"ח
--   מודעה 1051 — "יוקה פארק יוקה פארק", 254 מ"ר, 13,208 ש"ח
--
-- ‏`property_dedupe_key` בנוי מ-`(city, street, house_number, rooms,
-- floor, deal_type)`, ולשתיהן הוא זהה: עפולה · חרוד · 1 · null · null ·
-- rent. **המ"ר והמחיר אינם במפתח**, ובנכס מסחרי בלי חדרים ובלי קומה לא
-- נשאר במפתח שום דבר שמבדיל בין שתי יחידות באותו בניין.
--
-- זו הכרעת מוצר ולא תיקון נתונים: או שמודעה 1051 מיותרת, או שהיא צריכה
-- כתובת שמבדילה אותה. שתי התשובות הן של מנהל/ת הפלטפורמה, וניחוש כתובת
-- הוא בדיוק מה שאסור. הנכס נשאר עם הרחוב הנוכחי עד שתהיה הכרעה.

-- ---------------------------------------------------------------------------
-- 2. העתקה מנכסים באותה כתובת בדיוק
-- ---------------------------------------------------------------------------
with anchor as (
  select min(p.lat) as lat, min(p.lng) as lng
    from public.properties p
   where p.city = 'עפולה' and p.street = 'היצירה' and p.house_number = '5'
     and p.lat is not null and p.lng is not null
  having count(distinct round(p.lat::numeric, 6) || ',' || round(p.lng::numeric, 6)) = 1
)
update public.properties t
   set lat                  = anchor.lat,
       lng                  = anchor.lng,
       geocode_attempted_at = now(),
       geocode_error        = null
  from anchor
 where t.id in ('45deff96-430f-418a-8463-28f82ec97161',
                'd8097e4d-ccb5-43be-bf04-5d44c23e76f6')
   and (t.lat is null or t.lng is null);

-- ---------------------------------------------------------------------------
-- 3. "יוקה פארק" יורד מרשימת הרחובות
--
-- הוא נכנס לרישום כי הבאצ' הראשון (14.9.2026) נקלט מערכי
-- `properties.street` הקיימים - כלומר הוא **תוצאה** של הנתון השגוי ולא
-- הסיבה לו. כל רשומות ה-`legacy` נושאות את אותו `created_at`.
--
-- אחרי התיקון למעלה אף נכס אינו משתמש בו, אבל הוא נשאר ברשימה הנפתחת
-- בטופס - והטופס **חוסם** רחוב שאינו ברשימה, כלומר הרשימה היא מקור האמת.
-- מי שלא ינקה אותו, סוכן/ת הבא/ה תבחר בו שוב מהרשימה, והמחזור יתחיל מחדש.
--
-- התנאי `not exists` הוא מה שמונע מחיקה של רחוב שבכל זאת בשימוש: אם
-- התיקון למעלה לא תפס מסיבה כלשהי, הרשומה נשארת.
-- ---------------------------------------------------------------------------
delete from public.street_registry r
 where r.city = 'עפולה' and r.name = 'יוקה פארק'
   and not exists (select 1 from public.properties p
                    where p.city = 'עפולה' and p.street = r.name);

-- ---------------------------------------------------------------------------
-- מה נשאר
--
-- הנכס ששמו תוקן חוזר לתור ויקבל פין בסבב הקרוב. אם הוא ימצה שוב שלושה
-- ניסיונות, המשמעות היא ששם הרחוב עדיין אינו מה שהשכבה מכירה - וזו
-- תשובה שימושית בפני עצמה.
--
-- מודעה 1051 ממתינה להכרעה אנושית, ולכן היא עדיין תופיע ברשימת
-- "מיצו את התור".
-- ---------------------------------------------------------------------------
do $$
declare
  v_exhausted integer;
  v_queued    integer;
begin
  select count(*) into v_exhausted from public.properties
   where status = 'active' and (lat is null or lng is null) and geocode_attempts >= 3;
  select count(*) into v_queued from public.properties
   where status = 'active' and (lat is null or lng is null) and geocode_attempts = 0;
  raise notice 'מיצו את התור: % · ממתינים לסבב: %', v_exhausted, v_queued;
end $$;
