-- ---------------------------------------------------------------------------
-- 3. מודעה 1051 ("יוקה פארק"): חסומה בטריגר, וזה ממצא רחב יותר
--
-- ההכרעה התקבלה - הרחוב הוא `חרוד` ומספר הבית 1, כמו מודעה 1049 - אבל
-- ‏`properties_guard_duplicate` חוסם את העדכון, כי אחרי התיקון מפתח הכפילות
-- של שתי המודעות זהה: `עפולה|חרוד|1|||rent`.
--
-- ‏`property_dedupe_key` בנוי מ-`(city, street, house_number, rooms, floor,
-- deal_type)`. בנכס מסחרי `rooms` ו-`floor` ריקים, ולכן המפתח מתכווץ
-- **לכתובת בלבד** - ומתחם תעשייה בכתובת אחת מחזיק עשרות יחידות.
--
-- וזו אינה תקלה של מודעה אחת. נמדד מול המסד: **20 מודעות פעילות ב-9
-- כתובות חולקות מפתח כפילות ברגע זה**, כולן מסחריות, וכולן נכסים שונים
-- באמת:
--
--   יצחק רבין 1        4 מודעות   185 · 100 · 200 · 100 מ"ר
--   היצירה 5           4 מודעות   160 · 330 · 350 · 145 מ"ר
--   חרוד 1 (מכירה)     2 מודעות   2300 · 1000 מ"ר
--   ברזילאי 3          2 מודעות   1400 · 650 מ"ר
--   ועוד חמש כתובות
--
-- כלומר הטריגר אינו אוכף את הכלל הזה היום ממילא - הוא רק חוסם **שינוי**
-- של מודעה קיימת, בעוד שעשרים מודעות שכבר עברו יושבות באוויר. זו לא עקביות
-- שאפשר להשאיר.
--
-- ‏`size_sqm` מפריד 18 מתוך 20. הזוג היחיד שנשאר הוא 1044 ו-1062, שתיהן
-- ‏100 מ"ר ביצחק רבין 1, ושתיהן בבירור נכסים שונים: חנות פינתית במתחם
-- פנורמה ב-12,000 מול משרד בקומה 4 בבניין MCenter ב-2,500. שם מה שמפריד
-- הוא דווקא `floor`, שקיים בתיאור ולא הוזן לעמודה.
--
-- **התיקון הנכון אינו כאן, והוא הכרעת מוצר:** הרחבת `property_dedupe_key`
-- ב-`size_sqm` כש-`rooms` ו-`floor` ריקים. הוא נוגע באינדקס פונקציונלי
-- (`properties_dedupe_key_active_idx`), בארבע פונקציות נוספות, ובחתימה של
-- ‏`check_property_availability` - שאם לא תעודכן, בדיקת הכפילות בטופס תפסיק
-- להזהיר על נכסים מסחריים **בשקט**. והוא גם מחליש את ההגנה: שני משרדים
-- שידווחו 500 ו-505 מ"ר על אותה יחידה יעברו שניהם.
--
-- לכן הוא אינו נכנס כאן אגב תיקון כתובת. מודעה 1051 נשארת כפי שהיא.
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- אימות
-- ---------------------------------------------------------------------------
do $$
declare
  v_bad_streets integer;
  v_1068        text;
begin
  select count(*) into v_bad_streets from public.street_registry
   where city = 'עפולה' and name in ('יוקה פארק', 'ליד בנק הפועלים',
                                      'סביוני העמק שדרות רובע יזרעאל');
  select street into v_1068 from public.properties
   where id = '12fc1571-4e7b-43d5-b379-0b3f02b9f98f';
  raise notice 'הרחוב של 1068: % · רשומות שאינן רחוב שנותרו ברישום: %',
    coalesce(v_1068, 'לא נמצא'), v_bad_streets;
end $$;
