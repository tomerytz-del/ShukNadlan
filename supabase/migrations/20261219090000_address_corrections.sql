-- 2. מודעה 1066: "ליד בנק הפועלים" אינו רחוב, והרחוב הנכון אינו ידוע
--
-- הרשומה נשארת, והנכס נשאר, **בכוונה.** הציון "ליד בנק הפועלים" כבר יושב
-- בתיאור הנכס מילה במילה, ולכן אין מה להעביר לשם; מה שחסר הוא שם הרחוב
-- האמיתי, ואותו אין לנו.
--
-- ניחוש רחוב לפי הפין הוא בדיוק מה שאסור כאן: לנכס **יש** `lat`/`lng`
-- תקינים (32.601334, 35.2940907, באזור התעשייה), ולכן טעות בשם הרחוב לא
-- תתגלה בשום מקום - היא תיראה כמו נכס תקין לגמרי, עם פין, בכתובת שאינה
-- קיימת. עדיף ערך שגוי **גלוי** בשדה שאינו רחוב על פני ערך שגוי שנראה נכון.
--
-- מחיקת הרשומה מהרשימה לבדה הייתה גרועה יותר: הטופס חוסם רחוב שאינו
-- ברשימה, ולכן עריכה של המודעה הייתה נחסמת.
--
-- ממתין לשם הרחוב ממנהל/ת הפלטפורמה.
