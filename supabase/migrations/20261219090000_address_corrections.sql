-- שם פרויקט אינו שם רחוב
--
-- שלוש רשומות ב-`street_registry` של עפולה אינן רחובות, ושלושת הנכסים
-- שנשענים עליהן נושאים כתובת שהשכבה העירונית לעולם לא תכיר. ההכרעה בשלושתן
-- התקבלה מול מנהל/ת הפלטפורמה:
--
--   סביוני העמק שדרות רובע יזרעאל  ->  הרחוב הוא `שדרות רובע יזרעאל`
--   יוקה פארק                      ->  הרחוב הוא `חרוד`
--   ליד בנק הפועלים                ->  אינו רחוב, וזה חלק מתיאור הנכס
--
-- **הכלל:** שם פרויקט או ציון דרך נכנסים לכותרת ולתיאור, לא לשדה הרחוב.
-- שדה הרחוב הוא מפתח מול שכבת הכתובות של העירייה, ולכן ערך שאינו רחוב
-- מבטיח `address_not_found`, שלוש פעמים, ואז יציאה מהתור לצמיתות.
--
-- **ולמה זה מתגלגל:** `street_registry` הוא הרשימה הנפתחת בטופס, והטופס
-- חוסם רחוב שאינו בה. כלומר הערך השגוי אינו נשאר על נכס אחד - הוא מוצע
-- לסוכן/ת הבא/ה כאפשרות לגיטימית. לכן כל תיקון כאן הוא שניים: הנכס
-- והרשימה.
--
-- מתוך השלושה, רק אחד נסגר כאן במלואו. ראו למטה.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. מודעה 1068: "סביוני העמק" הוא הפרויקט, "שדרות רובע יזרעאל" הוא הרחוב
--
-- הרחוב הנכון כבר ברישום כ-`gis`, כלומר הוא מגיע משכבת הכתובות של העירייה
-- ומשמש שתי מודעות נוספות (1109 ו-1147).
--
-- נבדק לפני הכתיבה שהטריגר `properties_guard_duplicate` אינו חוסם: מפתח
-- הכפילות אחרי התיקון הוא `עפולה|שדרות רובע יזרעאל|20|4||sale`, ואין לו
-- אף נכס פעיל תואם.
--
-- הפין אינו נגזר מחדש. יש לנכס `lat`/`lng` ו-`geocode_attempts = 0`,
-- והנקודה יושבת כ-130 מטר ממודעה 1109 באותו רחוב - כלומר היא סבירה, ואין
-- סיבה להחזיר נכס עם פין תקין לתור.
-- ---------------------------------------------------------------------------
update public.properties
   set street  = 'שדרות רובע יזרעאל',
       address = 'שדרות רובע יזרעאל 20',
       title   = 'דירות, רובע יזרעאל שדרות רובע יזרעאל 20 - 120 מ"ר'
 where id = '12fc1571-4e7b-43d5-b379-0b3f02b9f98f'
   and street = 'סביוני העמק שדרות רובע יזרעאל';

-- שם הפרויקט עובר לתיאור, וזה המקום שאליו הוא שייך. התנאי `position` הופך
-- את השורה לאידמפוטנטית: הרצה שנייה לא תוסיף אותו פעמיים.
update public.properties
   set description = description || chr(10) || chr(10) || 'פרויקט סביוני העמק.'
 where id = '12fc1571-4e7b-43d5-b379-0b3f02b9f98f'
   and description is not null
   and position('סביוני העמק' in description) = 0;

delete from public.street_registry r
 where r.city = 'עפולה' and r.name = 'סביוני העמק שדרות רובע יזרעאל'
   and not exists (select 1 from public.properties p
                    where p.city = 'עפולה' and p.street = r.name);

