-- ============================================================================
-- "עלית", "ע עלית", "עפולה ע" - כינויים של עפולה עלית, מהקוד של האתר למסד
--
-- עד 21.10.2026 היו לשורת החיפוש באתר כינויים משלה, בקוד
-- (‏ALIASES ב-assets/sentence-search.js), ולבוטים בוואטסאפ - הכינויים
-- בטבלה הזו. שתי רשימות שונות לאותה שאלה: "דירה בגבעה" זוהה באתר, ו"דירה
-- בעלית" זוהה באתר ולא אצל גבריאלה. מעכשיו האתר טוען את הטבלה הזו, ושני
-- הצדדים מפענחים שם של אזור באותה פונקציה (‏SearchCore.findAreas,
-- docs/search-core.md).
--
-- "גבעה" כבר כאן (‏20270320091000). שלושת הכתיבים של עפולה עלית לא היו,
-- והם נכנסים כאן כדי שהאתר לא יאבד אותם כשהרשימה בקוד יורדת.
--
-- הטריגר `neighborhood_aliases_relink_deals` משייך מחדש את עסקאות העיר
-- מעצמו ("עלית" ברשות המסים בעפולה הוא עפולה עלית). ‏`on conflict do
-- nothing` - בטוחה להרצה חוזרת.
-- ============================================================================

insert into public.neighborhood_aliases (neighborhood_id, alias, shared, note)
select n.id, v.alias, false, v.note
  from (values
    ('עלית',     'כינוי שהיה בקוד של שורת החיפוש באתר (ALIASES), 21.10.2026'),
    ('ע עלית',   'כינוי שהיה בקוד של שורת החיפוש באתר (ALIASES), 21.10.2026'),
    ('עפולה ע',  'כינוי שהיה בקוד של שורת החיפוש באתר (ALIASES), 21.10.2026')
  ) as v(alias, note)
  join public.cities c on c.name = 'עפולה'
  join public.neighborhoods n on n.city_id = c.id and n.name = 'עפולה עלית'
on conflict (neighborhood_id, alias_key) do nothing;
