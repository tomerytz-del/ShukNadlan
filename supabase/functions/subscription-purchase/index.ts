// נפתח בלי תשלום ובלי כרטיס אשראי. התשלום היחיד הוא טעינת ארנק (wallet-topup),
// שממנה נרכשים לידים והקפצת נכסים.
//
// **למה הפונקציה נשארה כאן במקום להימחק.** ‏supabase_functions.yml פורס את מה
// שקיים בריפו ואינו מוחק את מה שנעלם ממנו. מחיקת התיקייה הייתה משאירה את
// הגרסה שכבר פרוסה חיה וקוראת — נקודת קצה שפותחת סליקת מנוי, בלי שום קוד
// מקור אצלנו שמסביר מה היא עושה. הסירוב כאן הוא מה שמבטל אותה בפועל, והוא
// נכנס לתוקף רק משום שהקובץ ממשיך להיפרס.
//
// ‏410 ולא 404: הנקודה קיימת, והיא נסגרה. לקוח ישן שמקבל 404 מנחש שטעה
// בכתובת ומנסה וריאציות; 410 אומר/ת שהמשאב הוסר לצמיתות.
//
// המסלול המלא שהיה כאן — start_subscription_purchase, טופס התשלום, והאישור
// ב-callback — נמחק במלואו ולא הושאר מאחורי דגל. דגל הוא מתג שאפשר להפוך
// בטעות; קוד שאינו קיים אינו יכול לרוץ. ההיסטוריה שמורה ב-git, וההסבר
// המלא ב-docs/wallet-payments.md.
// ============================================================================

Deno.serve((req: Request) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders() });

  return json({
    error: "subscription_purchase_disabled",
    detail:
      "אין רכישת מסלול. כל מי שמצטרף/ת למערכת נכנס/ת עם ההטבה, " +
      "והמסלול נפתח בלי תשלום. התשלום היחיד באתר הוא טעינת ארנק.",
  }, 410);
});
