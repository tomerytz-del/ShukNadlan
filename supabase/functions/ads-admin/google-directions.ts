// תבנית מודעה → טקסט לעיר הראשית של השוק.
export function fillCity(t: string, city: string): string {
  return t.replaceAll("{in_city}", inCity(city)).replaceAll("{city}", city);
}

// ב' צמודה לשם העיר. שם שמתחיל ב-ה' הידיעה נשאר כמו שהוא אחרי ב' ("בהרצליה").
export function inCity(name: string): string {
  return "ב" + name.trim();
}

// מונחי הזרע לכיוון, עם הערים שהתקבלו (הגדולות קודם). גוגל מקבלת עד 20
// מונחי זרע, ולכן הסדר הוא תבנית ואז עיר: כשהתקרה חותכת, נופלות התבניות
// האחרונות ברשימה בכל הערים, ולא עיר שלמה. סדר התבניות הוא סדר החשיבות.
export function seedsFor(d: Direction, cities: string[], maxSeeds = 20): string[] {
  const out = [...d.seeds];
  if (d.market) {
    for (const t of d.city_seeds) {
      for (const c of cities) {
        out.push(fillCity(t, c));
      }
    }
  }
  return [...new Set(out)].slice(0, maxSeeds);
}
