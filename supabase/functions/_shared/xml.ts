// ============================================================================
// בריחה לערך שנכנס לתוך XML - ‏`<fes:Literal>` בשאילתות ה-WFS של העירייה.
//
// השאילתות נבנות בשרשור מחרוזות, והערכים (רחוב, מספר בית, גוש, חלקה) מגיעים
// מבחוץ: מטופס הנכס, מהמסד, ומהעוזר בוואטסאפ - שם הם טקסט חופשי מהמודל.
// תו `<` או `&` אחד שובר את המסמך, השכבה עונה 400, ובמעלה הזרם זה נראה כמו
// "השכבה לא ענתה" על כתובת תקינה. גרוע מזה: ערך כמו
// `</fes:Literal></fes:PropertyIsEqualTo>...` משנה את הפילטר עצמו.
//
// זה אותו כלל של `escapeHtml` באתר (CLAUDE.md, "בריחת HTML"): עותק אחד, כל
// חמשת התווים. ‏`&` ראשון, אחרת הוא בורח שוב מהישויות שנוצרו.
// ============================================================================

export function xmlLiteral(value: unknown): string {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}
