// הרצה במקביל עם תקרה — לסבבי שליחה של cron
//
// שתי משימות השליחה (‏agent-reminders, ‏notification-push) עברו על הנמענים
// **בטור**: כל מייל דרך SMTP לוקח ~1.5 שניות, וכל הודעת וואטסאפ ~0.3, ולכן
// משך הסבב גדל ליניארית עם מספר הסוכנים. ב-12/09 זה נמדד בפרודקשן:
//
//   ‏claim ב-06:15:04.998 → מייל 1 ב-+2.1s · מייל 2 ב-+3.9s · מייל 3 ב-+4.9s
//
// שלושה סוכנים = כמעט חמש שניות, כלומר בדיוק על ברירת המחדל של `pg_net`
// שניתקה את החיבור. רביעי היה עובר אותה תמיד.
//
// ## למה תקרה ולא Promise.all
//
// ‏`BATCH` הוא 40. ‏`Promise.all` על ארבעים היה פותח ארבעים חיבורי SMTP
// במקביל מול Gmail, או ארבעים קריאות בבת אחת ל-Graph API — וזו הדרך לקבל
// חסימה זמנית מהספק במקום סבב מהיר. ספק שמדרג אותנו כמציף פוגע בכל הנמענים
// הבאים, לא רק בסבב הזה.
//
// ‏ארבעה במקביל מקצרים סבב של ארבעים משישים שניות לחמש-עשרה, ונשארים הרחק
// מכל מגבלת קצב סבירה.
//
// ## מה הפונקציה הזו מבטיחה
//
// ‏· סדר התוצאות זהה לסדר הקלט, גם כשההרצה עצמה מעורבבת.
// ‏· ‏`fn` שזורקת אינה מפילה את הסבב — כל קורא כאן עוטף בעצמו ב-try/catch
//   ומסמן כישלון ביומן, ולכן `mapPool` לא מנסה לתפוס במקומו.
// ============================================================================

export async function mapPool<T, R>(
  items: readonly T[],
  limit: number,
  fn: (item: T, index: number) => Promise<R>,
): Promise<R[]> {
  const results = new Array<R>(items.length);
  // מצביע משותף במקום חלוקה מראש לקבוצות: נמען אחד איטי לא מעכב את מי
  // שהיה "אחריו" בקבוצה שלו, והתקרה נשמרת לאורך כל הסבב.
  let next = 0;

  const worker = async () => {
    while (true) {
      const i = next++;
      if (i >= items.length) return;
      results[i] = await fn(items[i], i);
    }
  };

  const width = Math.max(1, Math.min(limit, items.length));
  await Promise.all(Array.from({ length: width }, worker));
  return results;
}
