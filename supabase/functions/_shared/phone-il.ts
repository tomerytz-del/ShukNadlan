// מספר טלפון של לקוח/ה או ליד לשליחת וואטסאפ. אותם כללים בדיוק כמו agenda_phone_e164 במסד
// (20271130120000_meeting_followup_optout_demo.sql), כדי שהשולח, הבוט והמסד יסכימו על מי נחסם,
// על מי עוצרים כשכותבים "הסר", ועל מי נשלחת הודעה.
//
// נפרד מ-phoneE164 הכללי (_shared/projects.ts), בכוונה: הוא משמש גם לטלפון של סוכן/ת ולקווים
// קוויים בקישורי wa.me, ולכן אינו קשוח. בקובץ נקי מייבוא, כדי שהבדיקה תרוץ ב-node.
//
// · 0 ואחריו 9 ספרות (נייד ישראלי)  -> 972 + 9 ספרות
// · 972 ואחריו 9 ספרות                -> כמו שהוא
// · קידומת מדינה אחרת (11-15 ספרות, לא מתחיל ב-0 וב-972) -> כמו שהוא
// · כל השאר (9 ספרות או פחות, קו קווי, 10 ספרות שאינן 0 ואחריו 9) -> null. 972 לא נוסף "לכל מספר קצר":
//   501234567 (אקסל שמוריד את האפס) אינו מספר שאפשר לשלוח אליו.

export function clientPhoneE164(value: unknown): string | null {
  if (typeof value !== "string") return null;
  let d = value.replace(/\D/g, "");
  if (d.startsWith("00")) d = d.slice(2);
  if (/^0[0-9]{9}$/.test(d)) return "972" + d.slice(1);
  if (/^972[0-9]{9}$/.test(d)) return d;
  if (/^[1-9][0-9]{10,14}$/.test(d) && !d.startsWith("972")) return d;
  return null;
}
