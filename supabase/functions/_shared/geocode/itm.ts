// רשת ישראל החדשה -> WGS84
//
// ‏**ITM / EPSG:2039 בלבד.** זה אינו ממיר גנרי: הוא נושא היסט דאטום בן שבעה
// פרמטרים שמתאים לרשת ישראל החדשה ולה בלבד. ‏X/Y מרשת ישראל **הישנה**
// (‏ICS, ‏Cassini-Soldner על Clarke 1880) שנכנסים לכאן **אינם מחזירים
// שגיאה** — הם מחזירים lat/lng סביר לגמרי, שגוי בכקילומטר. תיבת עיר של
// כ-13 ק"מ עוברת עליו בקלות.
//
// לכן הכלל: **כל מקור קואורדינטות רושם את הרשת שלו, ואינו מניח.**
//
// מה שנבדק עד כה, ושלושתם ITM:
//   - שכבת נקודות הכתובות של עיריית עפולה (המקור ההיסטורי של הקובץ הזה)
//   - קובץ היישובים של הלמ"ס, מול 76 פיני עפולה
//   - ‏GIS-Net של עיריית כרמיאל ו-GovMap, מול מחווני הקואורדינטות שלהם
//
// ## למה קובץ נפרד
//
// ההגדרה הזו ישבה **בשני עותקים זהים**, ב-afula-geocode.ts וב-
// afula-planning.ts. שבעה פרמטרי דאטום בשני מקומות פירושם שמי שיתקן אחד
// ולא את השני יקבל פינים שזזים במטרים **רק באחד משני המסלולים** — ההבדל
// בין הפין שבטופס הנכס לפין שבמידע התכנוני, על אותה כתובת.
// ============================================================================

import proj4 from "npm:proj4@2.9.0";

const ITM_DEF = "+proj=tmerc +lat_0=31.7343936111111 +lon_0=35.2045169444444 +k=1.0000067 +x_0=219529.584 +y_0=626907.39 +ellps=GRS80 +towgs84=23.772,17.49,17.859,-0.3132,-1.85274,1.67299,-5.4262 +units=m +no_defs +type=crs";
const WGS84_DEF = "+proj=longlat +datum=WGS84 +no_defs";

/** ‏[lng, lat] — שימו לב לסדר, זה הסדר ש-proj4 מחזיר ושהקוראים מפרקים. */
export function itmToWgs84(x: number, y: number): [number, number] {
  const [lng, lat] = proj4(ITM_DEF, WGS84_DEF, [x, y]);
  return [lng, lat];
}

/** הכיוון ההפוך, לשאילתות מרחביות שמקבלות ITM. */
export function wgs84ToItm(lat: number, lng: number): [number, number] {
  const [x, y] = proj4(WGS84_DEF, ITM_DEF, [lng, lat]);
  return [x, y];
}
