// ספרת הביקורת של ת.ז. ישראלית (וח״פ / מספר עמותה - אותו אלגוריתם).
//
// התאום בשרת של `assets/il-id.js`, באותו אלגוריתם ובאותן תוצאות: מספר קצר
// מרופד באפסים לתשע ספרות, כל ספרה מוכפלת לסירוגין ב-1 וב-2, מכפלה
// דו-ספרתית מתקפלת, והסכום מתחלק ב-10. שינוי כאן - שינוי גם שם.
//
// **הבדיקה תופסת טעות הקלדה, לא זהות.** לכן כל מי שמשתמש בה נותן גם דרך
// לאשר מספר שנפסל ("המספר נכון"): באתר תיבת סימון, בבוט `id_confirmed`.
// ---------------------------------------------------------------------------

export type IlIdStatus = "empty" | "ok" | "format" | "checksum";

export function ilIdStatus(v: unknown): IlIdStatus {
  const d = String(v ?? "").replace(/[\s\-.\/]/g, "");
  if (!d) return "empty";
  if (!/^\d{5,9}$/.test(d) || /^0+$/.test(d)) return "format";
  const p = d.padStart(9, "0");
  let sum = 0;
  for (let i = 0; i < 9; i++) {
    const n = Number(p[i]) * ((i % 2) + 1);
    sum += n > 9 ? n - 9 : n;
  }
  return sum % 10 === 0 ? "ok" : "checksum";
}
