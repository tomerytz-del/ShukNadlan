export const CSM_KIND_TIPS: Record<string, string> = {
  new_agent: "הימים הראשונים אחרי ההרשמה הם החלון. שיחה קצרה היום וקביעת פגישת הצלחה ראשונה עדיפות על הודעה ארוכה.",
  at_risk: "בלי אשמה ובלי \"למה לא\". פעולה אחת קטנה עם פקודה מוכנה לגבריאלה, ושאלה שקל לענות עליה בכן או לא.",
  meeting_reminder: "לצאת מהפגישה עם פעולה אחת שבוצעה בגבריאלה בזמן הפגישה, יעד שבועי אחד ומועד קשר.",
  call_ready: "ההודעה המוצעת עובדת הכי טוב באותו יום, כשהשיחה עוד טרייה.",
};

/** השורה שנוספת להתראה, או ריק לסוג בלי עצה קבועה (סיכום הבוקר, העצה היומית). */
export function kindTipLine(kind: string): string {
  const t = CSM_KIND_TIPS[kind];
  return t ? `💡 המנטור: ${t}` : "";
}

/** אחרי סיכום שיחה עם סוכן/ת והודעה מוצעת: איך שולחים אותה (csm_send_to_agent עם call_id). */
export function callFollowupHint(agentName: string | null): string {
  return `לשלוח ל${agentName ? agentName : "סוכן/ת"} את ההודעה המוצעת? כתבי "שלחי לו" (או "שלחי לה"), ואראה לך אותה לפני ששולחים.`;
}
